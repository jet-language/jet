#!/usr/bin/env node
// Regenerate the ratified-decision index in Docs/spec/syntax-decisions.md.
//
// A decision is ratified in Tower, and only some ratifications get
// hand-written prose in the spec. This writes a derived lookup of every
// ratified decision so that reading the spec is enough to find the outcome
// code depends on. The decision itself lives only in the Tower store; this
// index is never a second source of truth.
//
// Usage: node Tools/agent/decision-index.mjs [--check]

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const SPEC = join(ROOT, "Docs/spec/syntax-decisions.md");
const TOWER = join(ROOT, "Tools/tower/tower.mjs");
const OPEN = "<!-- BEGIN GENERATED RATIFIED INDEX -->";
const CLOSE = "<!-- END GENERATED RATIFIED INDEX -->";

const check = process.argv.includes("--check");

const raw = execFileSync(process.execPath, [TOWER, "decision", "list", "--json"], { cwd: ROOT, encoding: "utf8", maxBuffer: 1 << 30 });
const parsed = JSON.parse(raw);
const decisions = parsed.decisions ?? parsed;
if (!Array.isArray(decisions)) throw new Error("tower decision list --json returned no decision array");

const ratified = decisions
  .filter((decision) => decision.status === "ratified")
  .map((decision) => ({
    id: decision.id,
    outcome: String(decision.outcome ?? "").trim(),
    card: decision.cardId ?? "",
  }))
  .sort((left, right) => (left.id < right.id ? -1 : left.id > right.id ? 1 : 0));

// A verdict's outcome is a paragraph, not a letter. Keep the row scannable and
// let the reader follow the card for the wording.
const cell = (text) => {
  const flat = text.replace(/\s+/g, " ").replace(/\|/g, "\\|");
  return flat.length > 96 ? `${flat.slice(0, 93)}…` : flat;
};

const body = [
  OPEN,
  "",
  `Generated by \`Tools/agent/decision-index.mjs\` from the Tower store: ${ratified.length} ratified decisions.`,
  "Do not hand-edit these rows. The decision lives in Tower; this is a lookup so that reading this",
  "spec is enough to know the law. Sections above carry the teaching prose for decisions that changed",
  "user-typeable syntax; a row here with no prose above it is still binding.",
  "",
  "| Decision | Outcome | Card |",
  "| --- | --- | --- |",
  ...ratified.map((decision) => `| \`${decision.id}\` | ${cell(decision.outcome) || "—"} | \`${decision.card}\` |`),
  "",
  CLOSE,
].join("\n");

const spec = readFileSync(SPEC, "utf8");
const start = spec.indexOf(OPEN);
const end = spec.indexOf(CLOSE);
if (start === -1 || end === -1 || end < start) throw new Error(`${SPEC} has no generated ratified-index markers`);
const next = spec.slice(0, start) + body + spec.slice(end + CLOSE.length);

if (next === spec) {
  console.log(`decision index up to date (${ratified.length} ratified)`);
} else if (check) {
  console.error("decision index is stale; run: node Tools/agent/decision-index.mjs");
  process.exitCode = 1;
} else {
  writeFileSync(SPEC, next);
  console.log(`wrote decision index: ${ratified.length} ratified decisions`);
}
