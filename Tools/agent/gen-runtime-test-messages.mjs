#!/usr/bin/env node
// Fixed-width, heap-free literals for the native unit-test reporter.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const args = process.argv.slice(2);
if (args.some(arg => arg !== "--check") || args.length > 1) throw new Error("usage: gen-runtime-test-messages.mjs [--check]");
const literals = {
  invalid: "internal error: native test record is invalid\n",
  property_gap: "native property tests require a Jet property engine\n",
  pass: "pass", fail: "FAIL", skip: "skip", expected: "expected-fail",
  unexpected: "UNEXPECTED-PASS (remove expected_fail: true)",
  passed: " passed, ", failed: " failed, ", skipped: " skipped",
  expected_count: " expected-fail", unexpected_count: " unexpected-pass",
  shuffle: "shuffle: seed=",
  json_schema: '{"schema":"jet.test.v1","ok":',
  json_passed: ',"passed":', json_failed: ',"failed":', json_skipped: ',"skipped":',
  json_expected: ',"expectedFailures":', json_unexpected: ',"unexpectedPasses":',
  json_tests: ',"tests":[', json_name: '{"name":', json_ok: ',"ok":',
  json_expectation: ',"expectedFailure":', json_skip: ',"skipped":',
  json_stdout: ',"stdout":', json_stderr: ',"stderr":',
  true: "true", false: "false",
};
let source = "// Generated by Tools/agent/gen-runtime-test-messages.mjs; do not hand-edit.\n// Little-endian UTF-8 stack writes never construct a Rust String or exact Int.\n\n";
for (const [name, text] of Object.entries(literals)) {
  source += `fn test_msg_${name}(fd: I64) {\n`;
  const bytes = Buffer.from(text);
  for (let at = 0; at < bytes.length; at += 8) {
    const piece = bytes.subarray(at, at + 8);
    let word = 0n;
    for (let i = 0; i < piece.length; i++) word |= BigInt(piece[i]) << BigInt(8 * i);
    source += `    test_write_word(fd, I64{${BigInt.asIntN(64, word)}}, I64{${piece.length}})\n`;
  }
  source += "}\n\n";
}
// Environment keys are owned E4 text, borrowed only for the existing host leaf.
for (const [name, text] of Object.entries({json: "JET_TEST_JSON", capture: "JET_TEST_CAPTURE", shuffle: "JET_TEST_SHUFFLE_SEED"})) {
  const bytes = Buffer.from(text);
  source += `fn test_key_${name}() -> I64 {\n    text :: test_text_new(I64{${bytes.length}})\n    data :: trap_word(text)\n`;
  for (let i = 0; i < bytes.length; i++) source += `    trap_put(data + I64{${i}}, I64{${bytes[i]}})\n`;
  source += "    text\n}\n\n";
}
// Core.rs:678-860 / Outcome.rs:2502-2528 test-scope diagnostics use owned E4
// builders, sharing these fixed-width literal appenders with the reporter.
for (const [name, text] of Object.entries({
  expected: "expected ", region_stop: "this region to stop with ", region_fail: "this region to fail",
  stop_code: "a stop with ", stop_message: "a stop whose message contains ",
  code_message: " whose message contains ", passed: ", but it passed", got: ", got ",
  colon: ": ", timeout: "timeout: region took ", timeout_limit: "ns, limit was ", ns: "ns",
})) {
  source += `fn test_scope_msg_${name}(builder: I64) {\n`;
  const bytes = Buffer.from(text);
  for (let at = 0; at < bytes.length; at += 8) {
    const piece = bytes.subarray(at, at + 8);
    let word = 0n;
    for (let i = 0; i < piece.length; i++) word |= BigInt(piece[i]) << BigInt(8 * i);
    source += `    rt_text_push_word(builder, I64{${BigInt.asIntN(64, word)}}, I64{${piece.length}})\n`;
  }
  source += "}\n\n";
}
const ordinary = Buffer.from("__jet_test_ordinary_failure__");
source += `fn test_scope_ordinary(text: I64) -> Bool {\n    if (text == I64{0}) { return false }\n    if (trap_word(text + I64{8}) != I64{${ordinary.length}}) { return false }\n    data :: trap_word(text)\n`;
for (let i = 0; i < ordinary.length; i++) source += `    if (trap_byte(data + I64{${i}}) != I64{${ordinary[i]}}) { return false }\n`;
source += "    true\n}\n\n";
const target = resolve(root, "Compiler/JetRuntime/Source/TestMessages.jet");
if (args.includes("--check")) {
  if (readFileSync(target, "utf8") !== source) throw new Error("TestMessages.jet is stale");
} else writeFileSync(target, source);
