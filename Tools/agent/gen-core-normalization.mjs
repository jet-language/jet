#!/usr/bin/env node
// CLI-39: Core's UAX #15 tables, from the SAME pinned UCD as jet_unicode.
// Usage: node Tools/agent/gen-core-normalization.mjs [--check] [ucd-dir]
// The Rust generator owns the Unicode version/checksums. This projection checks
// each logical table against its committed Rust output before emitting Jet.
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import assert from "node:assert/strict";
import path from "node:path";

const check = process.argv[2] === "--check";
const ucd = process.argv[check ? 3 : 2] ?? "tests/data/unicode/ucd";
const generator = readFileSync("Tools/agent/gen-unicode-tables.mjs", "utf8");
const version = generator.match(/Pinned Unicode release: ([0-9.]+)\./)[1];
const pins = JSON.parse(generator.match(/const PINNED_SHA256 = (\{[\s\S]*?\n\});/)[1]
  .replace(/^\s*\/\/.*$/gm, "").replace(/,\s*}/g, "}"));
function input(name) {
  const bytes = readFileSync(path.join(ucd, name));
  assert.equal(createHash("sha256").update(bytes).digest("hex"), pins[name], `checksum: ${name}`);
  return bytes.toString("utf8");
}
const decompositions = [];
const ccc = [];
const pool = [];
for (const line of input("UnicodeData.txt").split("\n")) {
  if (!line) continue;
  const fields = line.split(";");
  if (fields.length < 14 || /, (First|Last)>$/.test(fields[1])) continue;
  const cp = parseInt(fields[0], 16);
  const cls = Number(fields[3]);
  if (cls) {
    const last = ccc.at(-1);
    if (last && last[1] + 1 === cp && last[2] === cls) last[1] = cp;
    else ccc.push([cp, cp, cls]);
  }
  if (fields[5]) {
    const canonical = fields[5].startsWith("<") ? 0 : 1;
    const children = fields[5].replace(/^<[^>]+>\s*/, "").trim().split(/\s+/).map(x => parseInt(x, 16));
    decompositions.push([cp, pool.length, children.length, canonical]);
    pool.push(...children);
  }
}
// Full_Composition_Exclusion includes primary, singleton and nonstarter exclusions.
input("CompositionExclusions.txt");
const excluded = [];
for (const raw of input("DerivedNormalizationProps.txt").split("\n")) {
  const fields = raw.split("#")[0].trim().split(";").map(x => x.trim());
  if (fields[1] !== "Full_Composition_Exclusion") continue;
  const [a, b = a] = fields[0].split("..").map(x => parseInt(x, 16));
  excluded.push([a, b]);
}
const pairs = [];
for (const [cp, start, length, canonical] of decompositions) {
  if (canonical && length === 2 && !excluded.some(([a, b]) => a <= cp && cp <= b)) {
    pairs.push([pool[start], pool[start + 1], cp]);
  }
}
pairs.sort((a, b) => a[0] - b[0] || a[1] - b[1]);
// Drift in the Rust generator or inputs must fail here, never silently ship two versions.
const rust = readFileSync("crates/jet-codegen/src/Prelude/CoreLib/Top/UnicodeTables.rs", "utf8");
assert.equal(rust.match(/UNICODE_VERSION: &str = "([^"]+)"/)[1], version);
function rustValues(name) {
  const body = rust.match(new RegExp(`pub static ${name}: [^=]+ = &\\[([^;]+)\\];`))[1];
  return [...body.matchAll(/0x[0-9A-F]+|\d+/g)].map(x => Number(x[0]));
}
for (const [name, values] of [
  ["UNICODE_DECOMP_POOL", pool], ["UNICODE_DECOMP_INDEX", decompositions.flat()],
  ["UNICODE_CCC", ccc.flat()], ["UNICODE_COMPOSE_PAIRS", pairs.flat()],
]) assert.deepEqual(values, rustValues(name), `Rust table drift: ${name}`);

function u21(n) {
  assert(n >= 0 && n <= 0x10FFFF);
  return [n >>> 16, (n >>> 8) & 255, n & 255];
}
function literal(name, bytes) {
  return `${name} :: [U8]{"${bytes.map(b => `\\x${b.toString(16).padStart(2, "0").toUpperCase()}`).join("")}"}\n`;
}
const begin = "// BEGIN GENERATED NORMALIZATION TABLES";
const end = "// END GENERATED NORMALIZATION TABLES";
const generated = `${begin}
// GENERATED by node Tools/agent/gen-core-normalization.mjs tests/data/unicode/ucd
// Unicode ${version}; checksum pins: Tools/agent/gen-unicode-tables.mjs (jet_unicode).
// Fixed-width, big-endian byte arrays; binary search never allocates table rows.
// Index: scalar:u21, pool_offset:u16, length:u8, canonical:u8 (${decompositions.length} rows).
${literal("C_NORMAL_DECOMP_INDEX", decompositions.flatMap(([cp, offset, length, canonical]) => {
  assert(offset <= 65535 && length <= 255);
  return [...u21(cp), offset >>> 8, offset & 255, length, canonical];
}))}// Pool: scalar:u21 (${pool.length} scalars).
${literal("C_NORMAL_DECOMP_POOL", pool.flatMap(u21))}// CCC ranges: start:u21, end:u21, class:u8 (${ccc.length} ranges).
${literal("C_NORMAL_CCC", ccc.flatMap(([a, b, c]) => [...u21(a), ...u21(b), c]))}// Composition: left:u21, right:u21, result:u21 (${pairs.length} pairs, exclusions applied).
${literal("C_NORMAL_COMPOSE", pairs.flatMap(row => row.flatMap(u21)))}${end}`;
const output = "Core/text/text.jet";
const current = readFileSync(output, "utf8");
const start = current.indexOf(begin);
const stop = current.indexOf(end, start) + end.length;
assert(start >= 0 && stop >= start + end.length, "normalization table markers missing");
const next = current.slice(0, start) + generated + current.slice(stop);
if (check) assert.equal(current, next, `${output} is stale`);
else writeFileSync(output, next);
console.log(`${check ? "checked" : "generated"}: ${output}; Unicode ${version}; ${decompositions.length} decompositions, ${ccc.length} CCC ranges, ${pairs.length} compositions`);
