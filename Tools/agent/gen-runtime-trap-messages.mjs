#!/usr/bin/env node
// Heap-free runtime stop literals. Keep the active diagnostic registry as the
// source of row prose. A literal longer than one word is one static text
// (`<name>_text`, which hand-written reports reuse) that the report writes in
// one call; a shorter one, and every host-defect row, is stack words through
// the audited stack-write OS leaf.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { staticText, staticTextWorthy } from "./runtime-static-text.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const registry = readFileSync(resolve(root, "Compiler/JetFoundation/Source/Registry/DiagnosticRows.jet"), "utf8");
const target = resolve(root, "Compiler/JetRuntime/Source/TrapMessages.jet");
const defectTarget = resolve(root, "Compiler/JetRuntime/Source/TrapDefectMessages.jet");
const check = process.argv.includes("--check");
const defectsOnly = process.argv.includes("--defects-only");
if (process.argv.slice(2).some((arg) => arg !== "--check" && arg !== "--defects-only")) throw new Error("usage: gen-runtime-trap-messages.mjs [--check] [--defects-only]");

function field(code, name) {
  const row = registry.split(/DiagnosticRegistryRow\{|\n    \{(?=\n        code:)/).find((row) => row.startsWith(`\n        code: "${code}",`));
  if (!row) throw new Error(`missing runtime row ${code}`);
  const value = new RegExp(`\\n        ${name}: ("(?:[^"\\\\]|\\\\.)*"),`).exec(row);
  if (!value) throw new Error(`missing ${code}.${name}`);
  return JSON.parse(value[1]).replaceAll("{{", "{").replaceAll("}}", "}");
}
// The native TLS refusal is defined once, in the IR route table that reports it at
// compile time; the runtime's stop and String-error leaves use this projection.
function nativeTlsRefusal() {
  const routes = readFileSync(resolve(root, "Compiler/JetIR/Source/RouteCarriers.jet"), "utf8");
  const value = /\nfn ir_tls_transport_message\(\) -> String Never! \{\n    ("(?:[^"\\]|\\.)*")\n\}/.exec(routes);
  if (!value) throw new Error("missing RouteCarriers.jet ir_tls_transport_message literal");
  const text = JSON.parse(value[1]);
  if (!/^[\x20-\x7e]+$/.test(text)) throw new Error("native TLS refusal must be printable ASCII for word projection");
  return text;
}
function emit(name, text, sink = "trap_write_word") {
  const bytes = Buffer.from(text);
  if (sink === "trap_write_word" && staticTextWorthy(text)) {
    return `fn ${name}_text() -> I64 { ${staticText(text)} }\n\n`
      + `fn ${name}() { trap_write_static(${name}_text()) }\n\n`
      + `fn trap_build_${name.slice(5)}(builder: I64) { jet_rt_string_builder_push(builder, ${name}_text()) }\n`;
  }
  let out = `fn ${name}() {\n`;
  let owned = `fn trap_build_${name.slice(5)}(builder: I64) {\n`;
  for (let at = 0; at < bytes.length; at += 8) {
    const piece = bytes.subarray(at, at + 8);
    let word = 0n;
    for (let i = 0; i < piece.length; i++) word |= BigInt(piece[i]) << BigInt(8 * i);
    // A signed machine literal preserves all eight little-endian bytes.
    out += `    ${sink}(I64{${BigInt.asIntN(64, word)}}, I64{${piece.length}})\n`
    if (sink === "trap_write_word") owned += `    rt_text_push_word(builder, I64{${BigInt.asIntN(64, word)}}, I64{${piece.length}})\n`
  }
  return sink === "trap_write_word" ? out + "}\n\n" + owned + "}\n" : out + "}\n";
}
let source = "// Generated by Tools/agent/gen-runtime-trap-messages.mjs; do not hand-edit.\n";
source += "// Process-static texts and little-endian UTF-8 word constants. No heap String,\n// allocation, mutable global, or numeric runtime is reached while writing these rows.\n\n";
for (const code of ["E3001", "E3010", "E3011", "E0128"]) {
  const why = field(code, "why");
  const fix = field(code, "fix");
  source += `// ${code} Why: ${why}\n// Fix: ${fix}\n`;
  source += emit(`trap_footer_${code.toLowerCase()}`, ` Why: ${why}\n Fix: ${fix}\nMore: jet-lang.dev/e/${code}\n`) + "\n";
}
// A failed `#Pre`/`#Post` clause (Trap.jet trap_contract_stop): the row's Why
// quotes the stop's own message at `{msg}`, so it is written in two pieces
// around that message.
const contractWhy = field("E3005", "why").split("{msg}");
if (contractWhy.length !== 2) throw new Error("E3005.why must quote {msg} exactly once");
const contractFix = field("E3005", "fix");
source += `// E3005 Why: ${contractWhy.join("{msg}")}\n// Fix: ${contractFix}\n`;
source += emit("trap_footer_e3005_head", ` Why: ${contractWhy[0]}`) + "\n";
source += emit("trap_footer_e3005_tail", `${contractWhy[1]}\n Fix: ${contractFix}\nMore: jet-lang.dev/e/E3005\n`) + "\n";
source += emit("trap_invalid_layout_head", `Stop [E3001]: ${field("E3001", "what").replace("{msg}", "invalid box layout")}\n  --> <core.prelude>:0\n`);
// A host stop whose code has no active runtime row is a Jet defect, not a
// diagnostic: no row speaks for it, so it prints one `internal error:` line
// with no Why, Fix or More. The code word sits between these two literals.
for (const code of ["E2805"]) {
  if (field(code, "stage").includes("runtime")) throw new Error(`${code} is an active runtime row; its stop renders the row, not the host form`);
}
// Core library stops that carry a registered code (core.rt.__coded_stop,
// Trap.jet jet_rt_coded_stop): the caller renders the row's `what`; the
// footer is the same row's Why/Fix. Codes are five-byte little-endian words.
const CODED_STOPS = ["E2804", "E2805"];
const codeWord = (code) => {
  if (!/^E\d{4}$/.test(code)) throw new Error(`${code} is not a five-byte diagnostic code`);
  let word = 0n;
  for (let i = 0; i < code.length; i++) word |= BigInt(code.charCodeAt(i)) << BigInt(8 * i);
  return word;
};
for (const code of CODED_STOPS) {
  const why = field(code, "why");
  const fix = field(code, "fix");
  source += `\n// ${code} Why: ${why}\n// Fix: ${fix}\n`;
  source += emit(`trap_footer_${code.toLowerCase()}`, ` Why: ${why}\n Fix: ${fix}\nMore: jet-lang.dev/e/${code}\n`);
}
source += `\nfn trap_coded_registered(code: I64) -> Bool {\n    ${CODED_STOPS.map((code) => `code == I64{${codeWord(code)}}`).join(" || ")}\n}\n`;
source += `\nfn trap_coded_footer(code: I64) {\n    if {\n${CODED_STOPS.slice(0, -1).map((code) => `        (code == I64{${codeWord(code)}}) -> trap_footer_${code.toLowerCase()}()\n`).join("")}        else -> trap_footer_${CODED_STOPS.at(-1).toLowerCase()}()\n    }\n}\n`;
const literals = {
  header_panic: "Stop [E3001]: " + field("E3001", "what").split("{msg}")[0],
  header_numeric: "Stop [E3010]: " + field("E3010", "what").split("{msg}")[0],
  header_todo: "Stop [E3011]: `",
  header_contract: "Stop [E3005]: ",
  header_zip: "Stop [E0128]: " + field("E0128", "what").split("{msg}")[0],
  zip_end: field("E0128", "what").split("{msg}")[1] + "\n",
  collections_end: "`\n  --> <core.collections>:0\n",
  sequence_count: "sequence count must be nonnegative",
  sequence_step: "step_by requires a positive step",
  sequence_chunks: "chunks requires a positive size",
  sequence_windows: "windows requires a positive size",
  cursor_step: "iterator loop stride must be positive",
  cursor_exhausted: "iterator loop value requested after exhaustion",
  location: "  --> ",
  colon: ":",
  in_function: " in ",
  newline: "\n",
  space: " ",
  gutter_line: "|\n",
  gutter_source: " | ",
  gutter_caret: "| ",
  caret: "^",
  message_end: "`\n",
  prelude_end: "`\n  --> <core.prelude>:0\n",
  overflow: "This arithmetic overflows the value's type (the result is outside its range)",
  divide_zero: "divided by zero",
  native_index_range: "native Int argument exceeds host range",
  list_head: "the list has ",
  // "1 item", otherwise "N items" (JetRuntime trap_list_count).
  list_item: " item",
  list_plural: "s",
  list_position: ", so position ",
  list_end: " doesn't exist`\n  --> <core.prelude>:0\n",
  // `bounds: report` (JetRuntime jet_rt_report_list_bounds): the failed
  // check's line, then its file and line; the program goes on.
  report_list_head: "bounds report: the list has ",
  report_list_at: " doesn't exist (",
  report_list_end: ")\n",
  unreachable: "internal error: entered unreachable code: ",
  locals: "locals: ",
  todo: "#Todo at ",
  todo_expected: " — expected ",
  expected: "expected: ",
  got: ", got: ",
  range_head: "can't ",
  range_slice: "slice",
  range_view: "view",
  range_items: " items from ",
  range_to: " to ",
  range_open: " (",
  exclusive: "exclusive",
  inclusive: "inclusive",
  range_end: ")`\n",
  native_tls: nativeTlsRefusal(),
  inactive_row_head: "internal error: runtime stop `",
  inactive_row_tail: "` has no active runtime row, so Jet cannot report it; please report this as a Jet defect",
  coded_head: "Stop [",
  coded_mid: "]: ",
};
for (const [name, text] of Object.entries(literals)) source += "\n" + emit(`trap_msg_${name}`, text);
// Retype the canonical Debug interval table at generation time. Runtime
// arithmetic stays fixed-width; only list indices cross the exact-Int seam.
const debug = readFileSync(resolve(root, "Compiler/JetFoundation/Source/Text/RustDebug.jet"), "utf8");
const boundaries = /\[Int\]\{([\s\S]*?)\}\s*\}/u.exec(debug);
if (!boundaries) throw new Error("missing Rust Debug scalar interval table");
const values = boundaries[1].match(/\d+/gu).map(Number);
if (values.length % 2 || values.some((value, i) => i && value < values[i - 1])) throw new Error("invalid Rust Debug intervals");
source += "\n// Canonical Text/RustDebug.jet intervals, retyped to machine words.\n";
source += `TRAP_DEBUG_RANGE_COUNT :: comptime { I64{${values.length / 2}} }\n`;
source += "TRAP_DEBUG_RANGES :: comptime { [I64]{\n";
for (let i = 0; i < values.length; i += 12) source += `    ${values.slice(i, i + 12).map((n) => `I64{${n}}`).join(", ")},\n`;
source += "} }\n";
// Both projections use the same canonical facts. Scoped private generation
// validates the frozen ordinary bytes first; default generation remains the
// canonical producer for both projections after the frozen gate is lifted.
let defects = "// Generated by Tools/agent/gen-runtime-trap-messages.mjs; do not hand-edit.\n";
defects += "// NO-TLS host-defect rows: raw stack-word writes only; no capture,\n// String carrier, allocation, callback, mutable global, or numeric runtime.\n\n";
defects += emit("trap_defect_unreachable_head", literals.unreachable, "trap_write_word_raw");
defects += "\n" + emit("trap_defect_newline", literals.newline, "trap_write_word_raw");
const sourceBytes = Buffer.from(source);
const defectBytes = Buffer.from(defects);
function readOutput(path) {
  try {
    return readFileSync(path);
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
    return null;
  }
}
const currentSource = readOutput(target);
const currentDefects = readOutput(defectTarget);
if (defectsOnly && !currentSource?.equals(sourceBytes)) {
  throw new Error("TrapMessages.jet differs from canonical facts; frozen output was not written");
}
if (check) {
  if (!currentSource?.equals(sourceBytes)) throw new Error("TrapMessages.jet is stale; run gen-runtime-trap-messages.mjs");
  if (!currentDefects?.equals(defectBytes)) throw new Error("TrapDefectMessages.jet is stale; run gen-runtime-trap-messages.mjs");
  console.log("runtime trap messages and private host-defect rows are current");
} else {
  if (!defectsOnly && !currentSource?.equals(sourceBytes)) writeFileSync(target, sourceBytes);
  if (!currentDefects?.equals(defectBytes)) writeFileSync(defectTarget, defectBytes);
}
