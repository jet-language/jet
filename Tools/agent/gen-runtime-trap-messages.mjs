#!/usr/bin/env node
// Heap-free runtime stop literals. Keep the active diagnostic registry as the
// source of row prose; emitted words use the audited stack-write OS leaf.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const registry = readFileSync(resolve(root, "Compiler/JetFoundation/Source/Registry/DiagnosticRows.jet"), "utf8");
const target = resolve(root, "Compiler/JetRuntime/Source/TrapMessages.jet");
const check = process.argv.includes("--check");
if (process.argv.slice(2).some((arg) => arg !== "--check")) throw new Error("usage: gen-runtime-trap-messages.mjs [--check]");

function field(code, name) {
  const row = registry.split("DiagnosticRegistryRow{").find((row) => row.startsWith(`\n        code: "${code}",`));
  if (!row) throw new Error(`missing runtime row ${code}`);
  const value = new RegExp(`\\n        ${name}: ("(?:[^"\\\\]|\\\\.)*"),`).exec(row);
  if (!value) throw new Error(`missing ${code}.${name}`);
  return JSON.parse(value[1]).replaceAll("{{", "{").replaceAll("}}", "}");
}
function emit(name, text) {
  const bytes = Buffer.from(text);
  let out = `fn ${name}() {\n`;
  for (let at = 0; at < bytes.length; at += 8) {
    const piece = bytes.subarray(at, at + 8);
    let word = 0n;
    for (let i = 0; i < piece.length; i++) word |= BigInt(piece[i]) << BigInt(8 * i);
    // A signed machine literal preserves all eight little-endian bytes.
    out += `    trap_write_word(I64{${BigInt.asIntN(64, word)}}, I64{${piece.length}})\n`;
  }
  return out + "}\n";
}
let source = "// Generated by Tools/agent/gen-runtime-trap-messages.mjs; do not hand-edit.\n";
source += "// Word constants are little-endian UTF-8. No String carrier, allocation,\n// mutable global, or numeric runtime is reached while writing these rows.\n\n";
for (const code of ["E3001", "E3010", "E3011", "E0128"]) {
  const why = field(code, "why");
  const fix = field(code, "fix");
  source += `// ${code} Why: ${why}\n// Fix: ${fix}\n`;
  source += emit(`trap_footer_${code.toLowerCase()}`, ` Why: ${why}\n Fix: ${fix}\nMore: jet-lang.dev/e/${code}\n`) + "\n";
}
source += emit("trap_invalid_layout_head", `Stop [E3001]: ${field("E3001", "what").replace("{msg}", "invalid box layout")}\n  --> <core.prelude>:0\n`);
const literals = {
  header_panic: "Stop [E3001]: " + field("E3001", "what").split("{msg}")[0],
  header_numeric: "Stop [E3010]: " + field("E3010", "what").split("{msg}")[0],
  header_todo: "Stop [E3011]: `",
  header_zip: "Stop [E0128]: " + field("E0128", "what").split("{msg}")[0],
  zip_end: field("E0128", "what").split("{msg}")[1] + "\n",
  collections_end: "`\n  --> <core.collections>:0\n",
  sequence_count: "sequence count must be nonnegative",
  sequence_step: "step_by requires a positive step",
  sequence_chunks: "chunks requires a positive size",
  sequence_windows: "windows requires a positive size",
  cursor_step: "iterator loop stride must be positive",
  cursor_exhausted: "iterator loop value requested after exhaustion",
  location: "  --> ",
  colon: ":",
  in_function: " in ",
  newline: "\n",
  space: " ",
  gutter_line: "|\n",
  gutter_source: " | ",
  gutter_caret: "| ",
  caret: "^",
  message_end: "`\n",
  prelude_end: "`\n  --> <core.prelude>:0\n",
  overflow: "This arithmetic overflows the value's type (the result is outside its range)",
  divide_zero: "divided by zero",
  native_index_range: "native Int argument exceeds host range",
  list_head: "the list has ",
  list_position: " items, so position ",
  list_end: " doesn't exist`\n  --> <core.prelude>:0\n",
  unreachable: "internal error: entered unreachable code: ",
  locals: "locals: ",
  todo: "#Todo at ",
  todo_expected: " — expected ",
  expected: "expected: ",
  got: ", got: ",
  range_head: "can't ",
  range_slice: "slice",
  range_view: "view",
  range_items: " items from ",
  range_to: " to ",
  range_open: " (",
  exclusive: "exclusive",
  inclusive: "inclusive",
  range_end: ")`\n",
};
for (const [name, text] of Object.entries(literals)) source += "\n" + emit(`trap_msg_${name}`, text);
// Retype the canonical Debug interval table at generation time. Runtime
// arithmetic stays fixed-width; only list indices cross the exact-Int seam.
const debug = readFileSync(resolve(root, "Compiler/JetFoundation/Source/Text/RustDebug.jet"), "utf8");
const boundaries = /\[Int\]\{([\s\S]*?)\}\s*\}/u.exec(debug);
if (!boundaries) throw new Error("missing Rust Debug scalar interval table");
const values = boundaries[1].match(/\d+/gu).map(Number);
if (values.length % 2 || values.some((value, i) => i && value < values[i - 1])) throw new Error("invalid Rust Debug intervals");
source += "\n// Canonical Text/RustDebug.jet intervals, retyped to machine words.\n";
source += `TRAP_DEBUG_RANGE_COUNT :: prep { I64{${values.length / 2}} }\n`;
source += "TRAP_DEBUG_RANGES :: prep { [I64]{\n";
for (let i = 0; i < values.length; i += 12) source += `    ${values.slice(i, i + 12).map((n) => `I64{${n}}`).join(", ")},\n`;
source += "} }\n";
if (check) {
  if (readFileSync(target, "utf8") !== source) throw new Error("TrapMessages.jet is stale; run gen-runtime-trap-messages.mjs");
  console.log("runtime trap messages are current");
} else writeFileSync(target, source);
