#!/usr/bin/env node
// Controlled-world and sentry literals use the runtime's existing E4 ABI.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const literals = {
  world_backwards: 'deterministic world cannot move time backwards; advance requires a non-negative duration',
  world_exhausted: 'deterministic world clock exhausted its supported range',
  world_budget: 'deterministic world execution budget exhausted while waiting for idle',
  world_live: 'deterministic world scope exited with live descendants; cancel and join every task',
  world_overflow: 'deterministic world timer overflowed',
  world_nested: 'deterministic world nesting is ambiguous; use the parent world explicitly',
  world_sleep: 'deterministic world sleep requires a controlled scheduler task',
  world_network: 'deterministic world has no controlled network provider',
  world_foreign: 'deterministic world has no controlled foreign provider',
  world_entropy: 'deterministic world has no controlled entropy provider',
  world_clock: 'deterministic world has no controlled clock provider',
  world_external: 'deterministic world has no controlled external-effect provider',
  spawn: 'task:spawn', finish: 'task:finish', advance: 'advance:',
  timer: 'timer:', register: 'timer:register:', rng: 'rng:', seed: 'rng:seed:', colon: ':', lf: '\n',
  sentry_location: '  --> ', sentry_gate: ', in #Unsafe gate ',
  sentry_read: 'read', sentry_valid_ptr: 'valid_ptr',
  sentry_why: ' Why: ', sentry_fix: '\n Fix: ',
  sentry_obligation: '\nobligation: valid_ptr = false\n',
  sentry_foreign: 'foreign: ', sentry_fenced: ' = fenced\n', sentry_unfenced: ' = unfenced\n',
  sentry_exit: 'exit: ',
  sentry_footer1: 'More: jet-lang.dev/e/R0801\n',
  sentry_footer2: 'More: jet-lang.dev/e/R0802\n',
  sentry_footer3: 'More: jet-lang.dev/e/R0803\n',
  sentry_provenance: 'no live allocation contains this address',
  sentry_bounds: 'the foreign access extends beyond a live allocation',
  sentry_heap: 'the address belongs to quarantined storage',
  sentry_stack: 'the owning Jet frame has expired',
  sentry_address: 'address 0x', sentry_alignment: ' is not aligned to ', sentry_bytes: ' bytes',
  ledger_key: 'JET_MEMORY_LEDGER', ledger_default: '.jet/memory/ledger-v1.jsonl',
  ledger_head: '{"schema":"jet.memory.ledger","version":1,"kind":"sentry","code":"R080',
  ledger_source: '","source":', ledger_start: ',"span_start":', ledger_end: ',"span_end":',
  ledger_scope: ',"byte_spans":false,"scope":', ledger_provenance: ',"provenance":"source #Unsafe gate","detail":',
  ledger_repairs: ',"expected":null,"repairs":',
  ledger_repairs1: '["derive the pointer from live storage inside this gate","remove the raw access"]}\n',
  ledger_repairs2: '["move the raw access before the storage is released","replace the raw pointer with an owned value"]}\n',
  ledger_repairs3: '["derive an aligned pointer from the live allocation","use the typed memory operation instead of raw address arithmetic"]}\n',
};
const registry = readFileSync(resolve(root, 'Compiler/JetFoundation/Source/Registry/DiagnosticRows.jet'), 'utf8');
for (const code of ['R0801', 'R0802', 'R0803']) {
  const row = registry.split('DiagnosticRegistryRow{').find(row => row.startsWith(`\n        code: "${code}",`));
  if (!row) throw new Error(`missing runtime row ${code}`);
  for (const name of ['what', 'why', 'fix']) {
    const value = new RegExp(`\\n        ${name}: ("(?:[^"\\\\]|\\\\.)*"),`).exec(row);
    if (!value) throw new Error(`missing ${code}.${name}`);
    literals[`sentry_${code.toLowerCase()}_${name}`] = JSON.parse(value[1]).replaceAll('{{', '{').replaceAll('}}', '}');
  }
}
let source = '// Generated by Tools/agent/gen-runtime-services-messages.mjs; owned E4 literals.\n';
for (const [name, text] of Object.entries(literals)) {
  const bytes = Buffer.from(text);
  source += `\nfn services_msg_${name}() -> I64 {\n    text :: scheduler_text_new(I64{${bytes.length}})\n    data :: sync_load(text)\n`;
  for (let i = 0; i < bytes.length; i += 8) {
    let word = 0n;
    for (let j = i; j < Math.min(i + 8, bytes.length); j++) word |= BigInt(bytes[j]) << BigInt((j - i) * 8);
    source += `    sync_store(data + I64{${i}}, I64{${BigInt.asIntN(64, word)}})\n`;
  }
  source += '    text\n}\n';
}
const target = resolve(root, 'Compiler/JetRuntime/Source/ServicesMessages.jet');
if (process.argv.slice(2).some(x => x !== '--check')) throw new Error('usage: gen-runtime-services-messages.mjs [--check]');
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== source) throw new Error('ServicesMessages.jet is stale');
  console.log('services messages are current');
} else writeFileSync(target, source);
