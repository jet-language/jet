#!/usr/bin/env node
// Pinned musl runtime-pack strerror data, never a libc runtime dependency.
// --refresh fetches the exact source assets; ordinary generation is offline.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { createHash } from "node:crypto";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const args = process.argv.slice(2);
if (args.length > 1 || args.some((arg) => !["--check", "--refresh"].includes(arg))) throw new Error("usage: gen-runtime-host-errors.mjs [--check|--refresh]");
const assets = join(root, "Compiler/JetRuntime/Assets/MuslErrno1_2_5");
const sources = [
  ["strerror.h", "src/errno/__strerror.h"],
  ["errno.h", "arch/generic/bits/errno.h"],
  ["COPYRIGHT", "COPYRIGHT"],
];
const hash = (bytes) => createHash("sha256").update(bytes).digest("hex");
const manifestPath = join(assets, "manifest.json");
if (args[0] === "--refresh") {
  mkdirSync(assets, { recursive: true });
  const prior = existsSync(manifestPath) ? JSON.parse(readFileSync(manifestPath, "utf8")) : null;
  const fetched = [];
  for (const [name, source] of sources) {
    const url = `https://git.musl-libc.org/cgit/musl/plain/${source}?h=v1.2.5`;
    const response = await fetch(url);
    if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
    const bytes = Buffer.from(await response.arrayBuffer());
    const sha256 = hash(bytes);
    if (prior && prior.files.find((row) => row.name === name)?.sha256 !== sha256) throw new Error(`${name}: upstream v1.2.5 changed; refuse an unreviewed asset update`);
    fetched.push({ name, source, url, sha256, bytes });
  }
  for (const { name, bytes } of fetched) writeFileSync(join(assets, name), bytes);
  writeFileSync(manifestPath, JSON.stringify({ version: "musl-1.2.5", license: "MIT", files: fetched.map(({ bytes, ...row }) => row) }, null, 2) + "\n");
}
const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
if (manifest.version !== "musl-1.2.5" || manifest.license !== "MIT") throw new Error("invalid errno source manifest");
for (const [name] of sources) {
  const bytes = readFileSync(join(assets, name));
  if (manifest.files.find((row) => row.name === name)?.sha256 !== hash(bytes)) throw new Error(`${name}: pinned errno asset changed`);
}
const definitions = new Map([...readFileSync(join(assets, "errno.h"), "utf8").matchAll(/^#define\s+(E\w+)\s+(\w+)\s*$/gm)].map((row) => [row[1], row[2]]));
function number(name, chain = new Set()) {
  if (/^\d+$/.test(name)) return Number(name);
  if (!definitions.has(name) || chain.has(name)) throw new Error(`unresolved errno ${name}`);
  return number(definitions.get(name), new Set([...chain, name]));
}
const messages = [...readFileSync(join(assets, "strerror.h"), "utf8").matchAll(/^E\((\w+),\s*("(?:[^"\\]|\\.)*")\)/gm)].map((row) => [number(row[1]), JSON.parse(row[2])]);
if (messages[0]?.[0] !== 0 || new Set(messages.map(([number]) => number)).size !== messages.length) throw new Error("invalid strerror source entries");
function words(text, indent) {
  const bytes = Buffer.from(text);
  const rows = [];
  for (let at = 0; at < bytes.length; at += 8) {
    const word = Buffer.alloc(8);
    bytes.copy(word, 0, at, Math.min(at + 8, bytes.length));
    rows.push(`${indent}rt_text_push_word(text, I64{${word.readBigInt64LE()}}, I64{${Math.min(8, bytes.length - at)}})`);
  }
  return rows;
}
// One static text holds the messages, a line per errno 0..highest in errno
// order, so a lookup costs a short scan instead of a branch and a push per
// message.
const highest = Math.max(...messages.map(([number]) => number));
const lines = Array.from({ length: highest + 1 }, () => "");
for (const [number, text] of messages) {
  if (!/^[\x20-\x7e]*$/.test(text) || /["\\{}]/.test(text)) throw new Error(`errno ${number}: message is not plain printable ASCII`);
  lines[number] = text;
}
const rows = [
  "// Generated by gen-runtime-host-errors.mjs from pinned musl 1.2.5 assets.",
  "// Source hashes and MIT attribution: Assets/MuslErrno1_2_5/manifest.json + COPYRIGHT.",
  "// Native-pack wording is musl, not GNU Rust-tier strerror wording.",
  "",
  `// The messages as one static text, a line per errno 0..${highest}, each ended`,
  "// by LF. An errno whose line is empty, or past the last, has line 0's.",
  "fn host_errno_append(text: I64, errno: I64) {",
  `    table :: rt_text_data(rt_static_text("${lines.map((line) => `${line}\\n`).join("")}"))`,
  `    index := if (errno > I64{0} && errno <= I64{${highest}}) -> errno else -> I64{0}`,
  "    loop {",
  "        start := I64{0}",
  "        line := I64{0}",
  "        loop line < index {",
  "            if (rt_text_byte(wrapping(table + start)) == I64{10}) -> line += I64{1}",
  "            start += I64{1}",
  "        }",
  "        end := start",
  "        loop rt_text_byte(wrapping(table + end)) != (I64{10}) -> end += I64{1}",
  "        if (end > start || index == I64{0}) {",
  "            rt_text_append(text, wrapping(table + start), end - start)",
  "            return",
  "        }",
  "        index = I64{0}",
  "    }",
  "}",
];
rows.push("", "fn host_errno_cause_append(text: I64, errno: I64) {", "    host_errno_append(text, errno)", ...words(" (os error ", "    "), "    rt_text_push_number(text, errno)", ...words(")", "    "), "}", "", "fn host_errno_text(errno: I64) -> I64 {", "    text :: jet_rt_string_builder_new()", "    host_errno_append(text, errno)", "    jet_rt_string_builder_finish(text)", "}", "", "fn host_errno_cause(errno: I64) -> I64 {", "    text :: jet_rt_string_builder_new()", "    host_errno_cause_append(text, errno)", "    jet_rt_string_builder_finish(text)", "}");
const text = rows.join("\n") + "\n";
const output = join(root, "Compiler/JetRuntime/Source/HostErrors.jet");
if (args[0] === "--check") {
  if (readFileSync(output, "utf8") !== text) throw new Error("HostErrors.jet is stale");
} else writeFileSync(output, text);
