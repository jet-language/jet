#!/usr/bin/env node
// Render the owner-controlled lexical ledger into the syntax decisions spec.
//
// Spellings.jet is the authority. This tool only reads its Jet table literal
// and replaces a marked Markdown block; it does not maintain a second spelling
// inventory or consult generated snapshots.
//
// Usage: node Tools/agent/lexical-ledger.mjs [--check|--write]

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
export const SYNTAX = "Compiler/JetFoundation/Data/Syntax/Spellings.jet";
const SPEC = "Docs/spec/syntax-decisions.md";
const OPEN = "<!-- BEGIN GENERATED LEXICAL LEDGER -->";
const CLOSE = "<!-- END GENERATED LEXICAL LEDGER -->";
const TABLE_RE = /^LEXICAL_LEDGER :: \[LexicalEntry\]\{[\s\S]*?\n\}/m;
const ROW_RE = /\{\s*spelling:\s*("(?:\\.|[^"\\])*"|[A-Za-z_][A-Za-z0-9_]*)\s*,\s*meaning:\s*("(?:\\.|[^"\\])*")\s*,\s*decision:\s*("(?:\\.|[^"\\])*")\s*\}/g;
const STRING_CONST_DECL_RE = /^([A-Za-z_][A-Za-z0-9_]*)\s*::/gm;
const STRING_CONST_LITERAL_RE = /^([A-Za-z_][A-Za-z0-9_]*)\s*::\s*("(?:\\.|[^"\\])*")\s*$/gm;

function readStringConstants(source) {
  const declarationCounts = new Map();
  STRING_CONST_DECL_RE.lastIndex = 0;
  for (const match of source.matchAll(STRING_CONST_DECL_RE)) {
    declarationCounts.set(match[1], (declarationCounts.get(match[1]) ?? 0) + 1);
  }

  const literals = new Map();
  STRING_CONST_LITERAL_RE.lastIndex = 0;
  for (const match of source.matchAll(STRING_CONST_LITERAL_RE)) {
    const values = literals.get(match[1]) ?? [];
    values.push(match[2]);
    literals.set(match[1], values);
  }

  return (name) => {
    const count = declarationCounts.get(name) ?? 0;
    if (count === 0) fail(`unresolved LexicalEntry spelling constant ${name} in ${SYNTAX}`);
    if (count !== 1) fail(`ambiguous LexicalEntry spelling constant ${name} in ${SYNTAX} (${count} declarations)`);
    const values = literals.get(name) ?? [];
    if (values.length !== 1) {
      fail(`LexicalEntry spelling constant ${name} in ${SYNTAX} must have a quoted string literal initializer`);
    }
    return jetString(values[0], `${name} spelling`);
  };
}

function fail(message) {
  throw new Error(`lexical ledger: ${message}`);
}

function readSource(path, root = ROOT) {
  try {
    return readFileSync(resolve(root, path), "utf8");
  } catch (error) {
    fail(`could not read ${path}: ${error instanceof Error ? error.message : String(error)}`);
  }
}

// A Jet string literal: `\` escapes and doubled braces (`{{`, `}}`) for literal
// braces. A single brace would be an interpolation, which the ledger never uses.
const JET_ESCAPES = { n: "\n", t: "\t", r: "\r", "0": "\0", "\\": "\\", '"': '"' };
function jetString(literal, field) {
  const body = literal.slice(1, -1);
  if (/[{}]/.test(body.replaceAll("{{", "").replaceAll("}}", ""))) {
    fail(`${field} string literal ${literal} interpolates; ledger rows must be literal text`);
  }
  return body.replace(/\\(.)|\{\{|\}\}/g, (match, escaped) => {
    if (match === "{{") return "{";
    if (match === "}}") return "}";
    if (!(escaped in JET_ESCAPES)) fail(`unsupported escape \\${escaped} in ${field} string literal ${literal}`);
    return JET_ESCAPES[escaped];
  });
}

export function readLedger(root = ROOT) {
  const source = readSource(SYNTAX, root);
  const table = source.match(TABLE_RE)?.[0];
  if (!table) fail(`missing ${SYNTAX}::LEXICAL_LEDGER table`);

  const resolveConstant = readStringConstants(source);
  const rows = [];
  const spellings = new Set();
  ROW_RE.lastIndex = 0;
  for (const match of table.matchAll(ROW_RE)) {
    const spelling = match[1].startsWith('"')
      ? jetString(match[1], "spelling")
      : resolveConstant(match[1]);
    if (spellings.has(spelling)) {
      fail(`duplicate LexicalEntry spelling ${JSON.stringify(spelling)} in ${SYNTAX}`);
    }
    spellings.add(spelling);
    rows.push({
      spelling,
      meaning: jetString(match[2], "meaning"),
      decision: jetString(match[3], "decision"),
    });
  }
  const literalCount = (table.match(/\{\s*spelling:/g) ?? []).length;
  if (rows.length === 0 || rows.length !== literalCount) {
    fail(`could not parse every LexicalEntry row in ${SYNTAX} (parsed ${rows.length}, found ${literalCount})`);
  }
  return rows;
}

function escapeHtml(value) {
  return value.replaceAll("&", "&amp;").replaceAll("<", "&lt;").replaceAll(">", "&gt;");
}

function cell(value) {
  const flat = String(value).replaceAll("|", "\\|").replaceAll(/\r?\n/g, " ");
  // A single backtick spelling cannot be represented by a one-backtick code
  // span. Use the equivalent inline HTML code element for those rows.
  return flat.includes("`") ? `<code>${escapeHtml(flat)}</code>` : `\`${flat}\``;
}

export function renderLedger(rows = readLedger()) {
  return [
    OPEN,
    "",
    `Generated by \`Tools/agent/lexical-ledger.mjs\` from \`${SYNTAX}::LEXICAL_LEDGER\`.`,
    "Do not hand-edit these rows. Add or change a spelling in Spellings.jet, recording its ratified decision ID when one exists, then rerun the renderer.",
    "",
    "| Spelling | Meaning | Decision |",
    "| --- | --- | --- |",
    ...rows.map((row) => `| ${cell(row.spelling)} | ${String(row.meaning).replaceAll("|", "\\|")} | ${row.decision ? cell(row.decision) : "—"} |`),
    "",
    CLOSE,
  ].join("\n");
}

function replaceBlock(spec, body) {
  const start = spec.indexOf(OPEN);
  const end = spec.indexOf(CLOSE);
  if ((start === -1) !== (end === -1)) fail("spec has only one lexical-ledger marker");
  if (start !== -1) {
    if (end < start) fail("spec lexical-ledger markers are out of order");
    return `${spec.slice(0, start)}${body}${spec.slice(end + CLOSE.length)}`;
  }

  const heading = "## Ratified\n";
  const anchor = spec.indexOf(heading);
  if (anchor === -1) fail("spec is missing the `## Ratified` insertion heading");
  const at = anchor + heading.length;
  return `${spec.slice(0, at)}\n${body}\n${spec.slice(at)}`;
}

function usage() {
  return [
    "usage: node Tools/agent/lexical-ledger.mjs [--check|--write]",
    "",
    "--check  fail when the rendered block is absent or stale",
    "--write  render the block from Spellings.jet into Docs/spec/syntax-decisions.md",
  ].join("\n");
}

export function main(argv = process.argv.slice(2)) {
  try {
    if (argv.includes("--help") || argv.includes("-h")) {
      process.stdout.write(`${usage()}\n`);
      return 0;
    }
    const unknown = argv.find((argument) => !["--check", "--write"].includes(argument));
    if (unknown) fail(`unknown option ${unknown}`);
    if (argv.includes("--check") && argv.includes("--write")) fail("choose --check or --write");

    const body = renderLedger();
    const spec = readSource(SPEC);
    const next = replaceBlock(spec, body);
    if (next === spec) {
      process.stdout.write(`lexical ledger up to date (${readLedger().length} rows)\n`);
      return 0;
    }
    if (argv.includes("--check")) {
      process.stderr.write("lexical ledger is stale; run: node Tools/agent/lexical-ledger.mjs --write\n");
      return 1;
    }
    writeFileSync(resolve(ROOT, SPEC), next);
    process.stdout.write(`wrote lexical ledger: ${readLedger().length} rows\n`);
    return 0;
  } catch (error) {
    process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
    return 1;
  }
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  process.exitCode = main();
}
