#!/usr/bin/env node
// Observe fragments append directly to the canonical E4 builder, without
// allocating an intermediate String for each fixed JSON/diagnostic fragment.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const literals = {
  task_label: 'task@', task_fallback: 'task #', site: ' (spawn site ', close_site: ')',
  yes: 'true', no: 'false', null: 'null', queued: 'queued', running: 'running', blocked: 'blocked', paused: 'paused',
  task_begin: '{"id":', parent: ',"parent":', label: ',"label":"', spawn: '","spawn_site":',
  state: ',"state":"', wait: '","wait":"', deadline: '","deadline_ms":', cancelled: ',"cancelled":',
  channel_begin: '{"id":', depth: ',"depth":', capacity: ',"capacity":', send_waiters: ',"send_waiters":', recv_waiters: ',"recv_waiters":', closed: ',"closed":',
  tasks: '"tasks":[', channels: '],"channels":[', end_arrays: ']}',
  entry: '\n  ', report_site: ' (spawn site ', report_state: ')\n    state: ', report_wait: '\n    wait target: ', unknown: 'unknown',
  omitted_head: '\n  ... ', omitted_tail: ' more parked task(s) omitted by the report limit ...',
};
let source = '// Generated by Tools/agent/gen-runtime-observe-messages.mjs; direct E4 builder fragments.\n';
for (const [name, text] of Object.entries(literals)) {
  const bytes = Buffer.from(text);
  source += `\nfn observe_msg_${name}(target: I64) {\n`;
  for (let i = 0; i < bytes.length; i += 8) {
    let word = 0n;
    for (let j = i; j < Math.min(i + 8, bytes.length); j++) word |= BigInt(bytes[j]) << BigInt((j - i) * 8);
    source += `    rt_text_push_word(target, I64{${BigInt.asIntN(64, word)}}, I64{${Math.min(8, bytes.length - i)}})\n`;
  }
  source += '}\n';
}
const target = resolve(root, 'Compiler/JetRuntime/Source/ObserveMessages.jet');
if (process.argv.slice(2).some(x => x !== '--check')) throw Error('usage: gen-runtime-observe-messages.mjs [--check]');
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== source) throw Error('ObserveMessages.jet is stale');
  console.log('observe messages are current');
} else writeFileSync(target, source);
