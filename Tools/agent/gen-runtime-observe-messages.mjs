#!/usr/bin/env node
// Observe fragments append directly to the canonical E4 builder, without
// allocating an intermediate String for each fixed JSON/diagnostic fragment.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const registry = readFileSync(resolve(root, 'Compiler/JetFoundation/Source/Registry/DiagnosticRows.jet'), 'utf8');
function field(name) {
  const row = registry.split('DiagnosticRegistryRow{').find(row => row.startsWith('\n        code: "E3013",'));
  if (!row) throw Error('missing runtime diagnostic E3013');
  const value = new RegExp(`\\n        ${name}: ("(?:[^"\\\\]|\\\\.)*"),`).exec(row);
  if (!value) throw Error(`missing E3013.${name}`);
  return JSON.parse(value[1]);
}
const literals = {
  task_label: 'task@', task_fallback: 'task #', site: ' (spawn site ', close_site: ')',
  yes: 'true', no: 'false', null: 'null', queued: 'queued', running: 'running', blocked: 'blocked', paused: 'paused',
  task_begin: '{"id":', parent: ',"parent":', label: ',"label":"', spawn: '","spawn_site":',
  state: ',"state":"', wait: '","wait":"', deadline: '","deadline_ms":', cancelled: ',"cancelled":',
  channel_begin: '{"id":', depth: ',"depth":', capacity: ',"capacity":', send_waiters: ',"send_waiters":', recv_waiters: ',"recv_waiters":', closed: ',"closed":',
  tasks: '"tasks":[', channels: '],"channels":[', end_arrays: ']}',
  entry: '\n  ', report_site: ' (spawn site ', report_state: ')\n    state: ', report_wait: '\n    wait target: ', unknown: 'unknown',
  omitted_head: '\n  ... ', omitted_tail: ' more parked task(s) omitted by the report limit ...',
  report_head: 'Stop [E3013]: ' + field('what').split('{msg}')[0],
  report_tail: field('what').split('{msg}')[1] + `\n Why: ${field('why')}\n Fix: ${field('fix')}\nMore: jet-lang.dev/e/E3013\n`,
  live_begin: '{"protocol":"jet.live.v1","session_id":"',
  live_source: '","source_id":"', live_build: '","build_id":"', live_revision: '","revision":"', live_world: '","world_id":"',
  live_decisions: '","decisions":', live_values: ',"values":[', live_schema: '],"schema_version":1,"pid":',
  live_start: ',"start_id":"', live_captured: '","captured_ms":', live_tasks: ',"tasks":[',
  live_events: '],"event_observations":[', live_effects: '],"effects":{"compute":',
  live_waiting: ',"waiting":', live_channel: ',"channel":', live_time: ',"time":', live_io: ',"io":',
  live_resources: '},"resources":{"workers":', live_running: ',"running":', live_queued: ',"queued":',
  live_cancelled: ',"cancelled":', live_arenas: ',"arenas":', live_allocs: ',"arena_allocations":', live_bytes: ',"arena_bytes":',
  live_runtime: '},"runtime":{"elapsed_ns":', live_cpu: ',"cpu_ns":', live_exit: ',"exit":', live_end: '}}',
  value_begin: '{"value_id":"', value_type: '","type_identity":"', value_disposition: '","disposition":"',
  value_reason: '","reason":"', value_rendered: '","rendered_value":',
  event_begin: '{"sequence":', event_source: ',"source":"', event_id: '","event_id":', event_owner: ',"owner_id":',
  event_subscription: ',"subscription_id":', event_dispatch: ',"dispatch_id":', event_lifecycle: ',"lifecycle":"',
  event_queued: '","queued":', event_blocked: ',"blocked":', event_running: ',"running":', event_capacity: ',"capacity":',
  event_overflow: ',"overflow":"', event_priority: '","priority":', event_failure: ',"failure":"', event_terminal: '","terminal":"',
  path_head: 'jet-observe-', path_tail: '.json', stage_head: '.jet-observe-', stage_tail: '.tmp',
  proc_stat: '/proc/self/stat', proc_auxv: '/proc/self/auxv',
  root_label: 'root',
  env_observe: 'JET_OBSERVE', env_session: 'JET_DEVTOOLS_RELAY_SESSION_ID', env_source: 'JET_DEVTOOLS_RELAY_SOURCE_ID',
  env_build: 'JET_DEVTOOLS_RELAY_BUILD_ID', env_revision: 'JET_DEVTOOLS_RELAY_REVISION', env_world: 'JET_DEVTOOLS_RELAY_WORLD_ID',
  env_tmpdir: 'TMPDIR', default_tmpdir: '/tmp',
};
let source = '// Generated by Tools/agent/gen-runtime-observe-messages.mjs; direct E4 builder fragments.\n';
for (const [name, text] of Object.entries(literals)) {
  const bytes = Buffer.from(text);
  source += `\nfn observe_msg_${name}(target: I64) {\n`;
  for (let i = 0; i < bytes.length; i += 8) {
    let word = 0n;
    for (let j = i; j < Math.min(i + 8, bytes.length); j++) word |= BigInt(bytes[j]) << BigInt((j - i) * 8);
    source += `    rt_text_push_word(target, I64{${BigInt.asIntN(64, word)}}, I64{${Math.min(8, bytes.length - i)}})\n`;
  }
  source += '}\n';
}
const target = resolve(root, 'Compiler/JetRuntime/Source/ObserveMessages.jet');
if (process.argv.slice(2).some(x => x !== '--check')) throw Error('usage: gen-runtime-observe-messages.mjs [--check]');
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== source) throw Error('ObserveMessages.jet is stale');
  console.log('observe messages are current');
} else writeFileSync(target, source);
