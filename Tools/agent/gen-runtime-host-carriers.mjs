#!/usr/bin/env node
// Host C carriers use the checked Core registry's declaration-order tags.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve, join } from "node:path";
import { fileURLToPath } from "node:url";
const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const args = process.argv.slice(2);
if (args.length > 1 || args.some((arg) => arg !== "--check")) throw new Error("usage: gen-runtime-host-carriers.mjs [--check]");
const source = "Compiler/JetFoundation/Source/Registry/CoreEnumPayloadRows.jet";
const rows = [...readFileSync(join(root, source), "utf8").matchAll(/CoreEnumPayloadRow\{enum_name: "([^"]+)", variant: "([^"]+)"/g)];
function variants(name) {
  const values = rows.filter((row) => row[1] === name).map((row) => row[2]);
  if (!values.length || new Set(values).size !== values.length) throw new Error(`missing/duplicate ${name} enum rows`);
  return values;
}
const kinds = variants("IOError"), operations = variants("IOOperation"), limits = variants("ProcessResourceLimit");
const jet = [`// Generated by gen-runtime-host-carriers.mjs from ${source}.`, "// C carrier tags are Core ordinals, not an independent runtime enum."];
for (const [name, values] of [["io_kind", kinds], ["io_op", operations], ["process_limit", limits]]) {
  for (const [index, value] of values.entries()) jet.push(`HOST_${name.toUpperCase()}_${value.replace(/([a-z])([A-Z])/g, "$1_$2").toUpperCase()} :: prep { I64{${index}} }`);
}
const rust = `// Generated by gen-runtime-host-carriers.mjs from ${source}.
// Native C boundaries copy into one fixed layout; Rust-tier kernels retain
// their Rust types. No Rust String/enum/Box layout crosses this boundary.
#[cfg(not(target_arch = "wasm32"))]
mod jet_c_abi_host {
    use crate::jet_c_abi::{handle, view, JetCString};
    use crate::jet_std::{IOContext, IOError, IOOperation, ProcessResourceLimit};

    #[repr(C)]
    pub(crate) struct JetCIOError {
        pub(crate) kind: i64,
        pub(crate) operation: i64,
        pub(crate) resource: JetCString,
        pub(crate) has_os_code: i64,
        pub(crate) os_code: i64,
        pub(crate) cause: JetCString,
        pub(crate) limit: i64,
    }
    unsafe extern "C" {
        fn jet_rt_alloc(size: usize, align: usize) -> *mut u8;
        fn jet_rt_handle_drop_IOError(value: *mut JetCIOError);
    }

    pub(crate) fn error_handle(value: IOError) -> *mut JetCIOError {
        let (kind, context, limit) = match value {
${kinds.map((kind, index) => kind === "ResourceLimit" ? `            IOError::${kind}(limit) => (${index}, None, match limit {\n${limits.map((value, index) => `                ProcessResourceLimit::${value} => ${index},`).join("\n")}\n            }),` : `            IOError::${kind}(context) => (${index}, Some(context), 0),`).join("\n")}
        };
        let (operation, resource, has_os_code, os_code, cause) = if let Some(context) = context {
            let operation = match context.operation {
${operations.map((value, index) => `                IOOperation::${value} => ${index},`).join("\n")}
            };
            let (has_os_code, os_code) = match context.os_code { Ok(code) => (1, code), Err(_) => (0, 0) };
            (operation, context.resource.ok().map(handle).unwrap_or(std::ptr::null_mut()), has_os_code, os_code,
                context.cause.ok().map(handle).unwrap_or(std::ptr::null_mut()))
        } else { (0, std::ptr::null_mut(), 0, 0, std::ptr::null_mut()) };
        // SAFETY: exactly one fresh 56-byte, eight-aligned owned carrier.
        let pointer = unsafe { jet_rt_alloc(56, 8) }.cast::<JetCIOError>();
        unsafe { pointer.write(JetCIOError { kind, operation, resource, has_os_code, os_code, cause, limit }) };
        pointer
    }

    pub(crate) fn error_view(pointer: *mut JetCIOError) -> IOError {
        // SAFETY: the caller lends the complete initialized C carrier and its
        // E4 text children. Returned Rust Strings are owned copies, not views.
        let value = unsafe { &*pointer };
        if value.kind == ${kinds.indexOf("ResourceLimit")} {
            return IOError::ResourceLimit(match value.limit {
${limits.map((name, index) => `                ${index} => ProcessResourceLimit::${name},`).join("\n")}
                _ => panic!("invalid ProcessResourceLimit C carrier"),
            });
        }
        let context = IOContext::new(match value.operation {
${operations.map((name, index) => `            ${index} => IOOperation::${name},`).join("\n")}
            _ => panic!("invalid IOOperation C carrier"),
        }, if value.resource.is_null() { None } else { Some(view(value.resource).to_owned()) },
            if value.has_os_code == 0 { None } else { Some(value.os_code) },
            if value.cause.is_null() { None } else { Some(view(value.cause).to_owned()) });
        match value.kind {
${kinds.filter((name) => name !== "ResourceLimit").map((name) => `            ${kinds.indexOf(name)} => IOError::${name}(context),`).join("\n")}
            _ => panic!("invalid IOError C carrier"),
        }
    }

    pub(crate) fn error_drop(pointer: *mut JetCIOError) {
        // SAFETY: this boundary consumes one carrier allocated by Jet.
        unsafe { jet_rt_handle_drop_IOError(pointer) };
    }
    pub(crate) fn error_take(pointer: *mut JetCIOError) -> IOError {
        let value = error_view(pointer);
        error_drop(pointer);
        value
    }
}
`;
for (const [path, text] of [["Compiler/JetRuntime/Source/HostEnums.jet", jet.join("\n") + "\n"], ["crates/jet-codegen/src/Prelude/Core/CAbiHost.rs", rust]]) {
  if (args[0] === "--check") {
    if (readFileSync(join(root, path), "utf8") !== text) throw new Error(`${path}: stale host carrier output`);
  } else writeFileSync(join(root, path), text);
}
