#!/usr/bin/env node
import { runtimeAbiAtom } from "./runtime-abi-symbols.mjs";
// Host C carriers use the checked Core registry's declaration-order tags.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve, join } from "node:path";
import { fileURLToPath } from "node:url";
const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const args = process.argv.slice(2);
if (args.length > 1 || args.some((arg) => arg !== "--check")) throw new Error("usage: gen-runtime-host-carriers.mjs [--check]");
const source = "Compiler/JetFoundation/Source/Registry/CoreEnumPayloadRows.jet";
const rows = [...readFileSync(join(root, source), "utf8").matchAll(/CoreEnumPayloadRow\{enum_name: "([^"]+)", variant: "([^"]+)"/g)];
function variants(name) {
  const values = rows.filter((row) => row[1] === name).map((row) => row[2]);
  if (!values.length || new Set(values).size !== values.length) throw new Error(`missing/duplicate ${name} enum rows`);
  return values;
}
const kinds = variants("IOError"), operations = variants("IOOperation"), limits = variants("ProcessResourceLimit");
const jet = [`// Generated by gen-runtime-host-carriers.mjs from ${source}.`, "// C carrier tags are Core ordinals, not an independent runtime enum."];
jet.push("// Refusals use the shared trap boundary: Root captures the full registered report.");
for (const [name, values] of [["io_kind", kinds], ["io_op", operations], ["process_limit", limits], ["process_stream", variants("ProcessStreamMode")], ["terminal_mode", variants("TerminalMode")]]) {
  for (const [index, value] of values.entries()) jet.push(`HOST_${name.toUpperCase()}_${value.replace(/([a-z])([A-Z])/g, "$1_$2").toUpperCase()} :: prep { I64{${index}} }`);
  jet.push(`HOST_${name.toUpperCase()}_COUNT :: prep { I64{${values.length}} }`);
}
// Registered E3001 stops: legacy writes are heap-free; Root owns the captured
// full report through the same trap_header / trap_footer publication boundary.
for (const [name, message] of [
  ["host_arguments_refused", "host arguments unavailable; call jet_rt_host_arguments before env or argv access"],
  ["host_environment_index_refused", "startup environment index out of range"],
  ["host_argument_index_refused", "startup argument index out of range"],
  ["host_record_index_refused", "record variant index out of range"],
  ["host_sigpipe_refused", "failed to initialize SIGPIPE handling"],
]) {
  jet.push("", `fn ${name}() {`, "    jet_rt_stdout_flush()", "    trap_header(I64{0})");
  const bytes = Buffer.from(message);
  for (let at = 0; at < bytes.length; at += 8) {
    const word = Buffer.alloc(8);
    bytes.copy(word, 0, at, Math.min(at + 8, bytes.length));
    jet.push(`    trap_write_word(I64{${word.readBigInt64LE()}}, I64{${Math.min(8, bytes.length - at)}})`);
  }
  jet.push("    trap_msg_prelude_end()", "    trap_footer(I64{0})", "}");
}
for (const [name, message] of [["host_stdout_name", "stdout"], ["host_stderr_name", "stderr"], ["host_write_zero_text", "failed to write whole buffer"], ["host_resolver_prefix", "failed to lookup address information: "], ["host_resolver_nul", "file name contained an unexpected NUL byte"], ["host_net_wait_kind", "network wait"]]) {
  jet.push("", `fn ${name}() -> I64 {`, "    text :: jet_rt_string_builder_new()");
  const bytes = Buffer.from(message);
  for (let at = 0; at < bytes.length; at += 8) {
    const word = Buffer.alloc(8);
    bytes.copy(word, 0, at, Math.min(at + 8, bytes.length));
    jet.push(`    rt_text_push_word(text, I64{${word.readBigInt64LE()}}, I64{${Math.min(8, bytes.length - at)}})`);
  }
  jet.push("    jet_rt_string_builder_finish(text)", "}");
}
for (const kind of kinds.filter((name) => name !== "ResourceLimit")) {
  const tag = `HOST_IO_KIND_${kind.replace(/([a-z])([A-Z])/g, "$1_$2").toUpperCase()}`;
  jet.push("", `#Export(c) fn jet_rt_record_get_io_error_${runtimeAbiAtom(kind)}(error: I64) -> I64 { host_error_context(error, ${tag}) }`,
    `#Export(c) fn jet_rt_record_new_io_error_${runtimeAbiAtom(kind)}(context: I64) -> I64 { host_error_with_context(context, ${tag}) }`);
}
const path = "Compiler/JetRuntime/Source/HostEnums.jet";
const text = jet.join("\n") + "\n";
const current = readFileSync(join(root, path), "utf8");
if (args[0] === "--check") {
  if (current !== text) throw new Error(`${path}: stale host carrier output`);
} else if (current !== text) writeFileSync(join(root, path), text);
