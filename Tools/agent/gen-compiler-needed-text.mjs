#!/usr/bin/env node
// Reproduce the compiler's allocation-free Unicode 17 property decisions from
// checksum-pinned UCD inputs. Balanced layout matches gen-unicode-tables.mjs;
// frozen range hashes preserve the former Rust table's exact parity oracle.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../../', import.meta.url));
const pinned = {
  'UnicodeData.txt': '2e1efc1dcb59c575eedf5ccae60f95229f706ee6d031835247d843c11d96470c',
  'DerivedCoreProperties.txt': '24c7fed1195c482faaefd5c1e7eb821c5ee1fb6de07ecdbaa64b56a99da22c08',
};
function checked(file) {
  const input = readFileSync(root + 'tests/data/unicode/ucd/' + file, 'utf8');
  if (createHash('sha256').update(input).digest('hex') !== pinned[file]) throw Error(`UCD checksum mismatch: ${file}`);
  return input;
}
const alphabetic = [];
for (const raw of checked('DerivedCoreProperties.txt').split('\n')) {
  const [extent, property] = raw.split('#')[0].split(';').map(value => value.trim());
  if (property !== 'Alphabetic') continue;
  const [lo, hi = lo] = extent.split('..').map(value => Number.parseInt(value, 16));
  alphabetic.push([lo, hi]);
}
const numeric = [];
let pending = null;
for (const raw of checked('UnicodeData.txt').split('\n')) {
  if (!raw) continue;
  const [hex, name, category] = raw.split(';');
  const cp = Number.parseInt(hex, 16);
  if (name.endsWith(', First>')) { pending = [cp, category]; continue; }
  if (name.endsWith(', Last>')) {
    if (!pending || pending[1] !== category) throw Error(`malformed UCD range: ${raw}`);
    if (['Nd', 'Nl', 'No'].includes(category)) numeric.push([pending[0], cp]);
    pending = null;
    continue;
  }
  if (['Nd', 'Nl', 'No'].includes(category)) numeric.push([cp, cp]);
}
if (pending) throw Error('unterminated UCD range');
const frozenRanges = {
  ALPHABETIC: '7de9ffd68b766619ca4c145a53801b407db2cdc618802232f5ceaf9871df8d73',
  NUMERIC: '7cf73db1c4a4a841517b6020051330dbedd6031a76bcd42a7096e0716838b8d4',
};
function ranges(name) {
  const rows = [];
  for (const [lo, hi] of (name === 'ALPHABETIC' ? alphabetic : numeric).sort((a, b) => a[0] - b[0])) {
    if (lo > hi || hi > 0x10ffff) throw Error(`invalid UCD range ${name}`);
    const last = rows.at(-1);
    if (last && lo <= last[1] + 1) last[1] = Math.max(last[1], hi);
    else rows.push([lo, hi]);
  }
  const serialized = rows.map(([lo, hi]) => `(0x${lo.toString(16).toUpperCase()},0x${hi.toString(16).toUpperCase()})`).join(',');
  const digest = createHash('sha256').update(serialized).digest('hex');
  if (digest !== frozenRanges[name]) throw Error(`frozen range parity mismatch: ${name}`);
  return { rows, digest };
}
function tree(rows, indent = '    ', mapped = () => 'true') {
  if (!rows.length) return `${indent}return false\n`;
  const mid = Math.floor(rows.length / 2);
  const row = rows[mid];
  function arm(guard, children) {
    if (!children.length) return `${indent}    ${guard} -> return false\n`;
    return `${indent}    ${guard} -> {\n${tree(children, indent + '        ', mapped)}${indent}    }\n`;
  }
  return `${indent}if {\n`
    + arm(`(cp < I64{${row[0]}})`, rows.slice(0, mid))
    + arm(`(cp > I64{${row[1]}})`, rows.slice(mid + 1))
    + `${indent}    else -> return ${mapped(row)}\n${indent}}\n`;
}
for (const name of ['ALPHABETIC', 'NUMERIC']) {
  const { rows, digest } = ranges(name);
  const header = '// Generated by Tools/agent/gen-compiler-needed-text.mjs; Unicode 17.0.0.\n'
    + `// Frozen UNICODE_${name} ranges SHA256 ${digest}; reproducible from pinned UCD.\n`
    + '// Static decisions: no allocation, Core calls, or locale dependency.\n';
  const label = name === 'ALPHABETIC' ? 'Alphabetic' : 'Numeric';
  const symbol = `compiler_text_${name.toLowerCase()}`;
  // Existing UnicodeNormalize generators also bound source-unit sizes: the
  // frozen parser's large-flat-unit path is quadratic, not a lookup policy.
  const chunks = [];
  if (name === 'ALPHABETIC') {
    for (let at = 0; at < rows.length; at += 96) {
      const part = rows.slice(at, at + 96), index = chunks.length;
      const helper = `${symbol}_${index}`;
      chunks.push([part[0][0], part.at(-1)[1], helper]);
      writeFileSync(root + `Compiler/JetRuntime/Source/CompilerNeededText${label}_${index}.jet`,
        header + `fn ${helper}(cp: I64) -> Bool Never! {\n${tree(part)}}\n`);
    }
  }
  const body = chunks.length ? tree(chunks, '    ', row => `${row[2]}(cp)`) : tree(rows);
  writeFileSync(root + `Compiler/JetRuntime/Source/CompilerNeededText${label}.jet`,
    header + `fn ${symbol}(cp: I64) -> Bool Never! {\n${body}}\n`);
}
