#!/usr/bin/env node
// The native fault report's machine code: assemble
// Compiler/JetRuntime/Assets/FaultReport/report.S (GNU as, from Jet's core
// shell: Tools/agent/jet-env node Tools/agent/gen-runtime-fault-report.mjs)
// and write its .text bytes as Compiler/JetBackend/Source/X64/FaultReport.jet.
// The bytes must need no relocation.
import { execFileSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const args = process.argv.slice(2);
if (args.length > 1 || args.some((arg) => arg !== "--check")) throw new Error("usage: gen-runtime-fault-report.mjs [--check]");
const sourcePath = "Compiler/JetRuntime/Assets/FaultReport/report.S";
const targetPath = "Compiler/JetBackend/Source/X64/FaultReport.jet";

const scratchRoot = process.env.JET_SCRATCH_ROOT || join(homedir(), ".cache/jet-dev/scratch");
mkdirSync(scratchRoot, { recursive: true });
const scratch = mkdtempSync(join(scratchRoot, "fault-report-"));
let object;
try {
  execFileSync("as", ["--64", "-o", join(scratch, "report.o"), join(root, sourcePath)], { stdio: ["ignore", "inherit", "inherit"] });
  object = readFileSync(join(scratch, "report.o"));
} finally {
  rmSync(scratch, { recursive: true, force: true });
}

// The ELF64 object's sections by name.
const shoff = Number(object.readBigUInt64LE(40));
const shentsize = object.readUInt16LE(58);
const shnum = object.readUInt16LE(60);
const names = shoff + object.readUInt16LE(62) * shentsize;
const namesAt = Number(object.readBigUInt64LE(names + 24));
const sections = new Map();
for (let index = 0; index < shnum; index++) {
  const header = shoff + index * shentsize;
  const nameAt = namesAt + object.readUInt32LE(header);
  const name = object.subarray(nameAt, object.indexOf(0, nameAt)).toString("latin1");
  sections.set(name, { offset: Number(object.readBigUInt64LE(header + 24)), size: Number(object.readBigUInt64LE(header + 32)) });
}
for (const name of sections.keys()) {
  if (name.startsWith(".rela") || name.startsWith(".rel.")) throw new Error(`${sourcePath}: ${name}: the report's bytes must need no relocation`);
}
for (const name of [".data", ".bss"]) {
  if ((sections.get(name)?.size ?? 0) !== 0) throw new Error(`${sourcePath}: ${name}: the report is code and texts only`);
}
const text = sections.get(".text");
if (!text || text.size === 0) throw new Error(`${sourcePath}: no .text`);
const bytes = [...object.subarray(text.offset, text.offset + text.size)];

let out = `// Generated by Tools/agent/gen-runtime-fault-report.mjs from\n// ${sourcePath}; do not hand-edit.\n`;
out += "// The native fault report's x86-64 code and texts: the body of the\n";
out += "// runtime's rt_fault_print leaf (JetIR BuildLibrary.jet). report.S\n";
out += "// documents how the bytes run.\n";
out += `X64_FAULT_REPORT :: [U8]{\n`;
for (let at = 0; at < bytes.length; at += 16) out += `    ${bytes.slice(at, at + 16).join(", ")},\n`;
out += "}\n";
const target = join(root, targetPath);
let current = null;
try { current = readFileSync(target, "utf8"); } catch {}
if (args[0] === "--check") {
  if (current !== out) throw new Error(`${targetPath} is stale; run gen-runtime-fault-report.mjs`);
  console.log(`runtime fault report is current (${bytes.length} bytes)`);
} else {
  if (current !== out) writeFileSync(target, out);
  console.log(`${targetPath}: ${bytes.length} bytes`);
}
