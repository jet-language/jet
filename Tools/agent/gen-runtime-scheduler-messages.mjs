#!/usr/bin/env node
// Scheduler literals have no implicit String/Int carrier in the runtime unit.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const literals = {
  threads: 'JET_SCHEDULER_THREADS', replay: 'JET_PROVE_REPLAY_TIME_MS', epoch: 'LEX_TEST_EPOCH',
  pause: 'task pause', join: 'task join', sleep: 'time sleep', yield: 'task yield', shield: 'shield exit', admission: 'task admission', selection: 'task selection',
  deadline_head: 'Error [E3003]: Deadline exceeded while waiting in ',
  deadline_tail: '\n Why: This wait point observed the task context deadline from `#Context(deadline: …)`\n Fix: Raise the deadline budget or shorten the work before this wait point\nMore: jet-lang.dev/e/E3003',
  cancelled: 'task cancelled at a cooperative wait point',
  trace_head: 'paused=', trace_mid: ',cancel=', yes: 'true', no: 'false',
  separator: ': ', start_failed: 'could not start scheduler worker', completion_exhausted: 'task completion order exhausted',
  rt_rate: 'real-time callback rate must be positive',
  rt_frames: 'real-time callback frame count must be positive',
  rt_native_range: 'native Int argument exceeds host range',
  rt_capacity: 'capacity overflow',
  rt_ring_frames: 'real-time sample ring needs a positive frame count',
  rt_self_join: 'failed to join real-time worker: Resource deadlock avoided',
  rt_join_failed: 'failed to join real-time worker',
  rt_start_failed: 'failed to spawn real-time worker',
};
let source = '// Generated by Tools/agent/gen-runtime-scheduler-messages.mjs; UTF-8 E4 literals.\n';
for (const [name, text] of Object.entries(literals)) {
  const bytes = Buffer.from(text);
  source += `\nfn scheduler_msg_${name}() -> I64 {\n    text :: scheduler_text_new(I64{${bytes.length}})\n    data :: sync_load(text)\n`;
  for (let i = 0; i < bytes.length; i += 8) {
    let word = 0n;
    for (let j = i; j < Math.min(i + 8, bytes.length); j++) word |= BigInt(bytes[j]) << BigInt((j - i) * 8);
    source += `    sync_store(data + I64{${i}}, I64{${BigInt.asIntN(64, word)}})\n`;
  }
  source += '    text\n}\n';
}
const target = resolve(root, 'Compiler/JetRuntime/Source/SchedulerMessages.jet');
if (process.argv.slice(2).some(x => x !== '--check')) throw new Error('usage: gen-runtime-scheduler-messages.mjs [--check]');
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== source) throw new Error('SchedulerMessages.jet is stale');
  console.log('scheduler messages are current');
} else writeFileSync(target, source);
