#!/usr/bin/env node
// Offline C witness goldens from pinned rustc 1.97.1's real PluginWire derives.
// Input TSV: tag, limit, frame_count, debug UTF-8 hex, display UTF-8 hex.
// Expected values are not native execution receipts.
import { readFileSync, writeFileSync } from 'node:fs';
const input = process.argv[2];
if (!input) throw new Error('usage: gen-plugin-debug-goldens.mjs <pinned-oracle.tsv>');
const rows = readFileSync(input, 'utf8').trimEnd().split('\n').map((line, index) => {
  const parts = line.split('\t');
  if (parts.length !== 5 || !/^[0-3]$/.test(parts[0]) || !/^[0-4]$/.test(parts[1]) || !/^(0|2)$/.test(parts[2]) || parts.slice(3).some(s => !/^(?:[0-9a-f]{2})*$/.test(s))) throw new Error(`invalid oracle row ${index}`);
  return parts;
});
const literal = hex => `"${hex.match(/../g)?.map(byte => `\\x${byte}`).join('') ?? ''}"`;
const header = '// GENERATED by Tools/agent/gen-plugin-debug-goldens.mjs.\n'
  + '// rustc 1.97.1 (8bab26f4f68e0e26f0bb7960be334d5b520ea452), real PluginWire.rs derives.\n'
  + '// Expected outputs, not native execution receipts.\n'
  + 'static const struct { int64_t tag, limit, frames; const char *debug, *display; int64_t debug_length, display_length; } plugin_goldens[] = {\n'
  + rows.map(([tag, limit, frames, debug, display]) => `    { ${tag}, ${limit}, ${frames}, ${literal(debug)}, ${literal(display)}, ${debug.length / 2}, ${display.length / 2} },\n`).join('') + '};\n';
writeFileSync('Compiler/JetRuntime/Tests/PluginErrorGoldens.h', header);
console.log(`plugin-error golden vectors: ${rows.length}; pinned rustc 1.97.1`);
