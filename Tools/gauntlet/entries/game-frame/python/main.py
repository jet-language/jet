canvas = bytearray(W * H * 4)
# The blend of premultiplied source byte `s` at alpha `a` over every target
# byte, as a bytes.translate table: one per (s, a) seen.
tables = {}


def mul(a, b):
    return (a * b + 127) // 255


def blend_table(source, alpha):
    key = (source << 8) | alpha
    table = tables.get(key)
    if table is None:
        table = bytes(source + mul(target, 255 - alpha) for target in range(256))
        tables[key] = table
    return table


def fill(x, y, width, height, color, replace):
    alpha = color & 255
    if width <= 0 or height <= 0 or (not replace and alpha == 0):
        return
    x0 = max(x, 0)
    y0 = max(y, 0)
    x1 = min(x + width, W)
    y1 = min(y + height, H)
    if x1 <= x0 or y1 <= y0:
        return
    red = mul(color >> 24, alpha)
    green = mul((color >> 16) & 255, alpha)
    blue = mul((color >> 8) & 255, alpha)
    if replace or alpha == 255:
        run = bytes((red, green, blue, alpha)) * (x1 - x0)
        for row in range(y0, y1):
            start = (row * W + x0) * 4
            canvas[start:start + len(run)] = run
        return
    channels = (blend_table(red, alpha), blend_table(green, alpha), blend_table(blue, alpha), blend_table(alpha, alpha))
    for row in range(y0, y1):
        start = (row * W + x0) * 4
        stop = (row * W + x1) * 4
        for channel in range(4):
            canvas[start + channel:stop:4] = canvas[start + channel:stop:4].translate(channels[channel])


def draw_text(text, x, y, size, color):
    scale = max((size + LINE // 2) // LINE, 1)
    pen_x = x
    pen_y = y
    for code in text.encode("utf-8"):
        if code == 10:
            pen_x = x
            pen_y += LINE * scale
            continue
        if 128 <= code < 192:
            continue
        glyph = code - 32 if 32 <= code <= 126 else 31
        for column in range(5):
            bits = FONT5X7[glyph * 5 + column]
            row = 0
            while row < 7:
                if (bits >> row) & 1 == 0:
                    row += 1
                    continue
                start = row
                while row < 7 and (bits >> row) & 1 != 0:
                    row += 1
                fill(pen_x + column * scale, pen_y + start * scale, scale, (row - start) * scale, color, False)
        pen_x += ADVANCE * scale


def end_drawing():
    path = os.environ.get("JET_FRAME_CAPTURE")
    if not path:
        return
    try:
        with open(path, "wb") as out:
            out.write(f"P7\nWIDTH {W}\nHEIGHT {H}\nDEPTH 4\nMAXVAL 255\nTUPLTYPE RGB_ALPHA\nENDHDR\n".encode())
            out.write(canvas)
    except OSError:
        pass


def rgba(r, g, b, a):
    return (r << 24) | (g << 16) | (b << 8) | a


def main():
    palette = [rgba(0, 0, 0, 0), rgba(52, 101, 164, 255), rgba(78, 154, 6, 255), rgba(196, 160, 0, 255)]
    sky = rgba(16, 20, 32, 255)
    bar = rgba(0, 0, 0, 160)
    white = rgba(255, 255, 255, 255)
    gold = rgba(255, 220, 120, 200)
    title = "JET RASTER"
    tiles = 0
    sprites = 0
    glyphs = 0
    for f in range(FRAMES):
        fill(0, 0, W, H, sky, True)
        scroll = f % 16
        base = f // 16
        for ty in range(12):
            for tx in range(21):
                p = ((tx + base) * 7 + ty * 5) % 4
                if p == 0:
                    continue
                fill(tx * 16 - scroll, ty * 16 + 8, 15, 15, palette[p], False)
                tiles += 1
        for i in range(48):
            x = (i * 41 + f * (1 + i % 4)) % 344 - 12
            y = (i * 29 + f * (1 + i % 3)) % 224 - 12
            fill(x, y, 12, 12, rgba((i * 53) % 256, (i * 97) % 256, (i * 31 + f) % 256, 180), False)
            sprites += 1
        fill(0, 0, W, 12, bar, False)
        hud = f"SCORE {(f * 7) % 100000} FRAME {f}"
        draw_text(hud, 4, 2, 10, white)
        draw_text(title, 196, 176, 20, gold)
        glyphs += len(hud) + len(title)
        end_drawing()
    print(f"frames={FRAMES} tiles={tiles} sprites={sprites} glyphs={glyphs}")


main()
