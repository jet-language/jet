// color is RGBA8 packed as 0xRRGGBBAA.
type color uint32

func rgba(r, g, b, a int) color {
	return color(uint32(r)<<24 | uint32(g)<<16 | uint32(b)<<8 | uint32(a))
}

func mul(a, b int) int { return (a*b + 127) / 255 }

type canvas [width * height * 4]byte

func (c *canvas) fill(x, y, w, h int, col color, replace bool) {
	alpha := int(col & 255)
	if w <= 0 || h <= 0 || (!replace && alpha == 0) {
		return
	}
	x0, y0 := max(x, 0), max(y, 0)
	x1, y1 := min(x+w, width), min(y+h, height)
	if x1 <= x0 || y1 <= y0 {
		return
	}
	red := byte(mul(int(col>>24), alpha))
	green := byte(mul(int(col>>16&255), alpha))
	blue := byte(mul(int(col>>8&255), alpha))
	rest := 255 - alpha
	opaque := replace || alpha == 255
	for row := y0; row < y1; row++ {
		span := c[(row*width+x0)*4 : (row*width+x1)*4]
		for at := 0; at < len(span); at += 4 {
			px := span[at : at+4 : at+4]
			if opaque {
				px[0], px[1], px[2], px[3] = red, green, blue, byte(alpha)
			} else {
				px[0] = red + byte(mul(int(px[0]), rest))
				px[1] = green + byte(mul(int(px[1]), rest))
				px[2] = blue + byte(mul(int(px[2]), rest))
				px[3] = byte(alpha + mul(int(px[3]), rest))
			}
		}
	}
}

func (c *canvas) drawText(text []byte, x, y, size int, col color) {
	scale := max((size+line/2)/line, 1)
	penX, penY := x, y
	for _, code := range text {
		if code == '\n' {
			penX = x
			penY += line * scale
			continue
		}
		if code >= 128 && code < 192 {
			continue
		}
		glyph := 31
		if code >= 32 && code <= 126 {
			glyph = int(code) - 32
		}
		for column := 0; column < 5; column++ {
			bits := font5x7[glyph*5+column]
			for row := 0; row < 7; {
				if bits>>row&1 == 0 {
					row++
					continue
				}
				start := row
				for row < 7 && bits>>row&1 != 0 {
					row++
				}
				c.fill(penX+column*scale, penY+start*scale, scale, (row-start)*scale, col, false)
			}
		}
		penX += advance * scale
	}
}

var pamHeader = fmt.Sprintf("P7\nWIDTH %d\nHEIGHT %d\nDEPTH 4\nMAXVAL 255\nTUPLTYPE RGB_ALPHA\nENDHDR\n", width, height)

func (c *canvas) endDrawing(capture string) {
	if capture == "" {
		return
	}
	file, err := os.Create(capture)
	if err != nil {
		return
	}
	file.WriteString(pamHeader)
	file.Write(c[:])
	file.Close()
}

func main() {
	palette := [4]color{rgba(0, 0, 0, 0), rgba(52, 101, 164, 255), rgba(78, 154, 6, 255), rgba(196, 160, 0, 255)}
	sky, bar := rgba(16, 20, 32, 255), rgba(0, 0, 0, 160)
	white, gold := rgba(255, 255, 255, 255), rgba(255, 220, 120, 200)
	title := []byte("JET RASTER")
	capture := os.Getenv("JET_FRAME_CAPTURE")
	var tiles, sprites, glyphs int
	c := new(canvas)
	hud := make([]byte, 0, 64)
	for f := 0; f < frames; f++ {
		c.fill(0, 0, width, height, sky, true)
		scroll, base := f%16, f/16
		for ty := 0; ty < 12; ty++ {
			for tx := 0; tx < 21; tx++ {
				p := ((tx+base)*7 + ty*5) % 4
				if p == 0 {
					continue
				}
				c.fill(tx*16-scroll, ty*16+8, 15, 15, palette[p], false)
				tiles++
			}
		}
		for i := 0; i < 48; i++ {
			x := (i*41+f*(1+i%4))%344 - 12
			y := (i*29+f*(1+i%3))%224 - 12
			c.fill(x, y, 12, 12, rgba((i*53)%256, (i*97)%256, (i*31+f)%256, 180), false)
			sprites++
		}
		c.fill(0, 0, width, 12, bar, false)
		hud = append(hud[:0], "SCORE "...)
		hud = strconv.AppendInt(hud, int64((f*7)%100000), 10)
		hud = append(hud, " FRAME "...)
		hud = strconv.AppendInt(hud, int64(f), 10)
		c.drawText(hud, 4, 2, 10, white)
		c.drawText(title, 196, 176, 20, gold)
		glyphs += len(hud) + len(title)
		c.endDrawing(capture)
	}
	fmt.Printf("frames=%d tiles=%d sprites=%d glyphs=%d\n", frames, tiles, sprites, glyphs)
}
