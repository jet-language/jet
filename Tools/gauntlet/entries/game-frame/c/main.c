uint8_t canvas[W * H * 4];

static uint32_t rgba(int r, int g, int b, int a) {
    return ((uint32_t)r << 24) | ((uint32_t)g << 16) | ((uint32_t)b << 8) | (uint32_t)a;
}

static int blend(int source, int target, int alpha) {
    return (source * alpha + target * (255 - alpha) + 127) / 255;
}

static void fill(int x, int y, int width, int height, uint32_t color, int replace) {
    int alpha = (int)(color & 255);
    if (width <= 0 || height <= 0 || (!replace && alpha == 0)) return;
    int x0 = x < 0 ? 0 : x, y0 = y < 0 ? 0 : y;
    int x1 = x + width < W ? x + width : W, y1 = y + height < H ? y + height : H;
    if (x1 <= x0 || y1 <= y0) return;
    int red = (int)(color >> 24), green = (int)((color >> 16) & 255), blue = (int)((color >> 8) & 255);
    int opaque = replace || alpha == 255;
    for (int row = y0; row < y1; ++row) {
        uint8_t *at = canvas + ((size_t)row * W + (size_t)x0) * 4;
        uint8_t *stop = canvas + ((size_t)row * W + (size_t)x1) * 4;
        for (; at < stop; at += 4) {
            if (opaque) {
                at[0] = (uint8_t)red;
                at[1] = (uint8_t)green;
                at[2] = (uint8_t)blue;
                at[3] = (uint8_t)alpha;
            } else {
                at[0] = (uint8_t)blend(red, at[0], alpha);
                at[1] = (uint8_t)blend(green, at[1], alpha);
                at[2] = (uint8_t)blend(blue, at[2], alpha);
                at[3] = (uint8_t)blend(alpha, at[3], alpha);
            }
        }
    }
}

static void draw_text(const char *text, int x, int y, int size, uint32_t color) {
    int scale = (size + LINE / 2) / LINE;
    if (scale < 1) scale = 1;
    int pen_x = x, pen_y = y;
    for (const unsigned char *p = (const unsigned char *)text; *p; ++p) {
        int code = *p;
        if (code == 10) {
            pen_x = x;
            pen_y += LINE * scale;
            continue;
        }
        if (code >= 128 && code < 192) continue;
        int glyph = code >= 32 && code <= 126 ? code - 32 : 31;
        for (int column = 0; column < 5; ++column) {
            int bits = FONT5X7[glyph * 5 + column];
            int row = 0;
            while (row < 7) {
                if (((bits >> row) & 1) == 0) {
                    row += 1;
                    continue;
                }
                int start = row;
                while (row < 7 && ((bits >> row) & 1) != 0) row += 1;
                fill(pen_x + column * scale, pen_y + start * scale, scale, (row - start) * scale, color, 0);
            }
        }
        pen_x += ADVANCE * scale;
    }
}

static void end_drawing(void) {
    const char *path = getenv("JET_RAYLIB_CAPTURE");
    if (!path || !*path) return;
    FILE *file = fopen(path, "wb");
    if (!file) return;
    fprintf(file, "P7\nWIDTH %d\nHEIGHT %d\nDEPTH 4\nMAXVAL 255\nTUPLTYPE RGB_ALPHA\nENDHDR\n", W, H);
    fwrite(canvas, 1, sizeof canvas, file);
    fclose(file);
}

int main(void) {
    const uint32_t palette[4] = {rgba(0, 0, 0, 0), rgba(52, 101, 164, 255), rgba(78, 154, 6, 255), rgba(196, 160, 0, 255)};
    const uint32_t sky = rgba(16, 20, 32, 255), bar = rgba(0, 0, 0, 160), white = rgba(255, 255, 255, 255), gold = rgba(255, 220, 120, 200);
    const char *title = "JET RASTER";
    long long tiles = 0, sprites = 0, glyphs = 0;
    char hud[64];
    memset(canvas, 0, sizeof canvas);
    for (int f = 0; f < FRAMES; ++f) {
        fill(0, 0, W, H, sky, 1);
        int scroll = f % 16, base = f / 16;
        for (int ty = 0; ty < 12; ++ty) {
            for (int tx = 0; tx < 21; ++tx) {
                int p = ((tx + base) * 7 + ty * 5) % 4;
                if (p == 0) continue;
                fill(tx * 16 - scroll, ty * 16 + 8, 15, 15, palette[p], 0);
                tiles += 1;
            }
        }
        for (int i = 0; i < 48; ++i) {
            int x = (i * 41 + f * (1 + i % 4)) % 344 - 12;
            int y = (i * 29 + f * (1 + i % 3)) % 224 - 12;
            fill(x, y, 12, 12, rgba((i * 53) % 256, (i * 97) % 256, (i * 31 + f) % 256, 180), 0);
            sprites += 1;
        }
        fill(0, 0, W, 12, bar, 0);
        int length = snprintf(hud, sizeof hud, "SCORE %d FRAME %d", (f * 7) % 100000, f);
        draw_text(hud, 4, 2, 10, white);
        draw_text(title, 196, 176, 20, gold);
        glyphs += length + (long long)strlen(title);
        end_drawing();
    }
    printf("frames=%d tiles=%lld sprites=%lld glyphs=%lld\n", FRAMES, tiles, sprites, glyphs);
    return 0;
}
