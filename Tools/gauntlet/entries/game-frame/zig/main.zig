var canvas = [_]u8{0} ** (W * H * 4);

fn rgba(r: i64, g: i64, b: i64, a: i64) u32 {
    return (@as(u32, @intCast(r)) << 24) | (@as(u32, @intCast(g)) << 16) | (@as(u32, @intCast(b)) << 8) | @as(u32, @intCast(a));
}

fn mul(a: u32, b: u32) u32 {
    return (a * b + 127) / 255;
}

fn fill(x: i64, y: i64, width: i64, height: i64, color: u32, replace: bool) void {
    const alpha = color & 255;
    if (width <= 0 or height <= 0 or (!replace and alpha == 0)) return;
    const x0 = @max(x, 0);
    const y0 = @max(y, 0);
    const x1 = @min(x + width, W);
    const y1 = @min(y + height, H);
    if (x1 <= x0 or y1 <= y0) return;
    const red = mul(color >> 24, alpha);
    const green = mul((color >> 16) & 255, alpha);
    const blue = mul((color >> 8) & 255, alpha);
    const rest = 255 - alpha;
    const opaque_fill = replace or alpha == 255;
    var row = y0;
    while (row < y1) : (row += 1) {
        var at: usize = @intCast((row * W + x0) * 4);
        const stop: usize = @intCast((row * W + x1) * 4);
        while (at < stop) : (at += 4) {
            if (opaque_fill) {
                canvas[at] = @intCast(red);
                canvas[at + 1] = @intCast(green);
                canvas[at + 2] = @intCast(blue);
                canvas[at + 3] = @intCast(alpha);
            } else {
                canvas[at] = @intCast(red + mul(canvas[at], rest));
                canvas[at + 1] = @intCast(green + mul(canvas[at + 1], rest));
                canvas[at + 2] = @intCast(blue + mul(canvas[at + 2], rest));
                canvas[at + 3] = @intCast(alpha + mul(canvas[at + 3], rest));
            }
        }
    }
}

fn drawText(text: []const u8, x: i64, y: i64, size: i64, color: u32) void {
    const scale = @max(@divTrunc(size + @divTrunc(LINE, 2), LINE), 1);
    var pen_x = x;
    var pen_y = y;
    for (text) |byte| {
        const code: i64 = byte;
        if (code == 10) {
            pen_x = x;
            pen_y += LINE * scale;
            continue;
        }
        if (code >= 128 and code < 192) continue;
        const glyph: i64 = if (code >= 32 and code <= 126) code - 32 else 31;
        var column: i64 = 0;
        while (column < 5) : (column += 1) {
            const bits: i64 = FONT5X7[@intCast(glyph * 5 + column)];
            var row: i64 = 0;
            while (row < 7) {
                if ((bits >> @intCast(row)) & 1 == 0) {
                    row += 1;
                    continue;
                }
                const start = row;
                while (row < 7 and (bits >> @intCast(row)) & 1 != 0) row += 1;
                fill(pen_x + column * scale, pen_y + start * scale, scale, (row - start) * scale, color, false);
            }
        }
        pen_x += ADVANCE * scale;
    }
}

fn endDrawing(init: std.process.Init) void {
    const path = init.environ_map.get("JET_FRAME_CAPTURE") orelse return;
    if (path.len == 0) return;
    const file = std.Io.Dir.cwd().createFile(init.io, path, .{}) catch return;
    defer file.close(init.io);
    var header: [96]u8 = undefined;
    const text = std.fmt.bufPrint(&header, "P7\nWIDTH {d}\nHEIGHT {d}\nDEPTH 4\nMAXVAL 255\nTUPLTYPE RGB_ALPHA\nENDHDR\n", .{ W, H }) catch return;
    file.writeStreamingAll(init.io, text) catch return;
    file.writeStreamingAll(init.io, &canvas) catch return;
}

pub fn main(init: std.process.Init) !void {
    const palette = [4]u32{ rgba(0, 0, 0, 0), rgba(52, 101, 164, 255), rgba(78, 154, 6, 255), rgba(196, 160, 0, 255) };
    const sky = rgba(16, 20, 32, 255);
    const bar = rgba(0, 0, 0, 160);
    const white = rgba(255, 255, 255, 255);
    const gold = rgba(255, 220, 120, 200);
    const title = "JET RASTER";
    var tiles: i64 = 0;
    var sprites: i64 = 0;
    var glyphs: i64 = 0;
    var hud_buffer: [64]u8 = undefined;
    var f: i64 = 0;
    while (f < FRAMES) : (f += 1) {
        fill(0, 0, W, H, sky, true);
        const scroll = @mod(f, 16);
        const base = @divTrunc(f, 16);
        var ty: i64 = 0;
        while (ty < 12) : (ty += 1) {
            var tx: i64 = 0;
            while (tx < 21) : (tx += 1) {
                const p = @mod((tx + base) * 7 + ty * 5, 4);
                if (p == 0) continue;
                fill(tx * 16 - scroll, ty * 16 + 8, 15, 15, palette[@intCast(p)], false);
                tiles += 1;
            }
        }
        var i: i64 = 0;
        while (i < 48) : (i += 1) {
            const x = @mod(i * 41 + f * (1 + @mod(i, 4)), 344) - 12;
            const y = @mod(i * 29 + f * (1 + @mod(i, 3)), 224) - 12;
            fill(x, y, 12, 12, rgba(@mod(i * 53, 256), @mod(i * 97, 256), @mod(i * 31 + f, 256), 180), false);
            sprites += 1;
        }
        fill(0, 0, W, 12, bar, false);
        const hud = try std.fmt.bufPrint(&hud_buffer, "SCORE {d} FRAME {d}", .{ @mod(f * 7, 100000), f });
        drawText(hud, 4, 2, 10, white);
        drawText(title, 196, 176, 20, gold);
        glyphs += @intCast(hud.len + title.len);
        endDrawing(init);
    }
    var out_buffer: [128]u8 = undefined;
    var out = std.Io.File.Writer.init(.stdout(), init.io, &out_buffer);
    try out.interface.print("frames={d} tiles={d} sprites={d} glyphs={d}\n", .{ FRAMES, tiles, sprites, glyphs });
    try out.interface.flush();
}
