const canvas = new Uint8Array(W * H * 4);

function rgba(r, g, b, a) {
  return ((r << 24) | (g << 16) | (b << 8) | a) >>> 0;
}

function blend(source, target, alpha) {
  return Math.trunc((source * alpha + target * (255 - alpha) + 127) / 255);
}

function fill(x, y, width, height, color, replace) {
  const alpha = color & 255;
  if (width <= 0 || height <= 0 || (!replace && alpha === 0)) return;
  const x0 = Math.max(x, 0);
  const y0 = Math.max(y, 0);
  const x1 = Math.min(x + width, W);
  const y1 = Math.min(y + height, H);
  if (x1 <= x0 || y1 <= y0) return;
  const red = color >>> 24;
  const green = (color >>> 16) & 255;
  const blue = (color >>> 8) & 255;
  const opaque = replace || alpha === 255;
  for (let row = y0; row < y1; row += 1) {
    const stop = (row * W + x1) * 4;
    for (let at = (row * W + x0) * 4; at < stop; at += 4) {
      if (opaque) {
        canvas[at] = red;
        canvas[at + 1] = green;
        canvas[at + 2] = blue;
        canvas[at + 3] = alpha;
      } else {
        canvas[at] = blend(red, canvas[at], alpha);
        canvas[at + 1] = blend(green, canvas[at + 1], alpha);
        canvas[at + 2] = blend(blue, canvas[at + 2], alpha);
        canvas[at + 3] = blend(alpha, canvas[at + 3], alpha);
      }
    }
  }
}

function drawText(text, x, y, size, color) {
  const scale = Math.max(Math.trunc((size + LINE / 2) / LINE), 1);
  let penX = x;
  let penY = y;
  for (const code of Buffer.from(text, "utf8")) {
    if (code === 10) {
      penX = x;
      penY += LINE * scale;
      continue;
    }
    if (code >= 128 && code < 192) continue;
    const glyph = code >= 32 && code <= 126 ? code - 32 : 31;
    for (let column = 0; column < 5; column += 1) {
      const bits = FONT5X7[glyph * 5 + column];
      let row = 0;
      while (row < 7) {
        if (((bits >> row) & 1) === 0) {
          row += 1;
          continue;
        }
        const start = row;
        while (row < 7 && ((bits >> row) & 1) !== 0) row += 1;
        fill(penX + column * scale, penY + start * scale, scale, (row - start) * scale, color, false);
      }
    }
    penX += ADVANCE * scale;
  }
}

function endDrawing() {
  const path = process.env.JET_RAYLIB_CAPTURE;
  if (!path) return;
  try {
    const header = Buffer.from(`P7\nWIDTH ${W}\nHEIGHT ${H}\nDEPTH 4\nMAXVAL 255\nTUPLTYPE RGB_ALPHA\nENDHDR\n`);
    writeFileSync(path, Buffer.concat([header, canvas]));
  } catch {
    // A capture that cannot be written is skipped.
  }
}

const palette = [rgba(0, 0, 0, 0), rgba(52, 101, 164, 255), rgba(78, 154, 6, 255), rgba(196, 160, 0, 255)];
const sky = rgba(16, 20, 32, 255);
const bar = rgba(0, 0, 0, 160);
const white = rgba(255, 255, 255, 255);
const gold = rgba(255, 220, 120, 200);
const title = "JET RASTER";
let tiles = 0;
let sprites = 0;
let glyphs = 0;
for (let f = 0; f < FRAMES; f += 1) {
  fill(0, 0, W, H, sky, true);
  const scroll = f % 16;
  const base = Math.trunc(f / 16);
  for (let ty = 0; ty < 12; ty += 1) {
    for (let tx = 0; tx < 21; tx += 1) {
      const p = ((tx + base) * 7 + ty * 5) % 4;
      if (p === 0) continue;
      fill(tx * 16 - scroll, ty * 16 + 8, 15, 15, palette[p], false);
      tiles += 1;
    }
  }
  for (let i = 0; i < 48; i += 1) {
    const x = ((i * 41 + f * (1 + (i % 4))) % 344) - 12;
    const y = ((i * 29 + f * (1 + (i % 3))) % 224) - 12;
    fill(x, y, 12, 12, rgba((i * 53) % 256, (i * 97) % 256, (i * 31 + f) % 256, 180), false);
    sprites += 1;
  }
  fill(0, 0, W, 12, bar, false);
  const hud = `SCORE ${(f * 7) % 100000} FRAME ${f}`;
  drawText(hud, 4, 2, 10, white);
  drawText(title, 196, 176, 20, gold);
  glyphs += hud.length + title.length;
  endDrawing();
}
