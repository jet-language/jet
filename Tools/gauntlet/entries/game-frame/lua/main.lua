-- The canvas: W * H pixels of four bytes, index 1 holding pixel 0's red.
local canvas = {}
for i = 1, W * H * 4 do
  canvas[i] = 0
end

local function mul(a, b)
  return floor((a * b + 127) / 255)
end

-- A color is {r, g, b, a}.
local function fill(x, y, width, height, color, replace)
  local alpha = color[4]
  if width <= 0 or height <= 0 or (not replace and alpha == 0) then
    return
  end
  local x0, y0 = max(x, 0), max(y, 0)
  local x1, y1 = min(x + width, W), min(y + height, H)
  if x1 <= x0 or y1 <= y0 then
    return
  end
  local red, green, blue = mul(color[1], alpha), mul(color[2], alpha), mul(color[3], alpha)
  if replace or alpha == 255 then
    for row = y0, y1 - 1 do
      for at = (row * W + x0) * 4 + 1, (row * W + x1) * 4, 4 do
        canvas[at], canvas[at + 1], canvas[at + 2], canvas[at + 3] = red, green, blue, alpha
      end
    end
    return
  end
  local rest = 255 - alpha
  for row = y0, y1 - 1 do
    for at = (row * W + x0) * 4 + 1, (row * W + x1) * 4, 4 do
      canvas[at] = red + floor((canvas[at] * rest + 127) / 255)
      canvas[at + 1] = green + floor((canvas[at + 1] * rest + 127) / 255)
      canvas[at + 2] = blue + floor((canvas[at + 2] * rest + 127) / 255)
      canvas[at + 3] = alpha + floor((canvas[at + 3] * rest + 127) / 255)
    end
  end
end

local function draw_text(text, x, y, size, color)
  local scale = max(floor((size + floor(LINE / 2)) / LINE), 1)
  local pen_x, pen_y = x, y
  for k = 1, #text do
    local code = text:byte(k)
    if code == 10 then
      pen_x = x
      pen_y = pen_y + LINE * scale
    elseif code < 128 or code >= 192 then
      local glyph = (code >= 32 and code <= 126) and code - 32 or 31
      for column = 0, 4 do
        local bits = FONT5X7[glyph * 5 + column + 1]
        local row = 0
        while row < 7 do
          if bits % 2 == 0 then
            row = row + 1
            bits = floor(bits / 2)
          else
            local start = row
            while row < 7 and bits % 2 == 1 do
              row = row + 1
              bits = floor(bits / 2)
            end
            fill(pen_x + column * scale, pen_y + start * scale, scale, (row - start) * scale, color, false)
          end
        end
      end
      pen_x = pen_x + ADVANCE * scale
    end
  end
end

local PAM_HEADER = string.format("P7\nWIDTH %d\nHEIGHT %d\nDEPTH 4\nMAXVAL 255\nTUPLTYPE RGB_ALPHA\nENDHDR\n", W, H)

local function end_drawing(capture)
  if not capture or capture == "" then
    return
  end
  local out = io.open(capture, "wb")
  if not out then
    return
  end
  out:write(PAM_HEADER)
  local stride = W * 4
  for row = 0, H - 1 do
    out:write(string.char(unpack(canvas, row * stride + 1, (row + 1) * stride)))
  end
  out:close()
end

local palette = { { 0, 0, 0, 0 }, { 52, 101, 164, 255 }, { 78, 154, 6, 255 }, { 196, 160, 0, 255 } }
local sky, bar = { 16, 20, 32, 255 }, { 0, 0, 0, 160 }
local white, gold = { 255, 255, 255, 255 }, { 255, 220, 120, 200 }
local title = "JET RASTER"
local capture = os.getenv("JET_FRAME_CAPTURE")
local tiles, sprites, glyphs = 0, 0, 0
for f = 0, FRAMES - 1 do
  fill(0, 0, W, H, sky, true)
  local scroll, base = f % 16, floor(f / 16)
  for ty = 0, 11 do
    for tx = 0, 20 do
      local p = ((tx + base) * 7 + ty * 5) % 4
      if p ~= 0 then
        fill(tx * 16 - scroll, ty * 16 + 8, 15, 15, palette[p + 1], false)
        tiles = tiles + 1
      end
    end
  end
  for i = 0, 47 do
    local x = (i * 41 + f * (1 + i % 4)) % 344 - 12
    local y = (i * 29 + f * (1 + i % 3)) % 224 - 12
    fill(x, y, 12, 12, { (i * 53) % 256, (i * 97) % 256, (i * 31 + f) % 256, 180 }, false)
    sprites = sprites + 1
  end
  fill(0, 0, W, 12, bar, false)
  local hud = string.format("SCORE %d FRAME %d", (f * 7) % 100000, f)
  draw_text(hud, 4, 2, 10, white)
  draw_text(title, 196, 176, 20, gold)
  glyphs = glyphs + #hud + #title
  end_drawing(capture)
end
io.write(string.format("frames=%d tiles=%d sprites=%d glyphs=%d\n", FRAMES, tiles, sprites, glyphs))
