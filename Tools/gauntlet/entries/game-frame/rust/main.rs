fn rgba(r: i64, g: i64, b: i64, a: i64) -> u32 {
    ((r as u32) << 24) | ((g as u32) << 16) | ((b as u32) << 8) | a as u32
}

fn mul(a: u32, b: u32) -> u32 {
    (a * b + 127) / 255
}

fn fill(canvas: &mut [u8], x: i64, y: i64, width: i64, height: i64, color: u32, replace: bool) {
    let alpha = color & 255;
    if width <= 0 || height <= 0 || (!replace && alpha == 0) {
        return;
    }
    let x0 = x.max(0);
    let y0 = y.max(0);
    let x1 = (x + width).min(W);
    let y1 = (y + height).min(H);
    if x1 <= x0 || y1 <= y0 {
        return;
    }
    let (red, green, blue) = (mul(color >> 24, alpha), mul((color >> 16) & 255, alpha), mul((color >> 8) & 255, alpha));
    let rest = 255 - alpha;
    let opaque = replace || alpha == 255;
    for row in y0..y1 {
        let start = ((row * W + x0) * 4) as usize;
        let stop = ((row * W + x1) * 4) as usize;
        for pixel in canvas[start..stop].chunks_exact_mut(4) {
            if opaque {
                pixel[0] = red as u8;
                pixel[1] = green as u8;
                pixel[2] = blue as u8;
                pixel[3] = alpha as u8;
            } else {
                pixel[0] = (red + mul(pixel[0] as u32, rest)) as u8;
                pixel[1] = (green + mul(pixel[1] as u32, rest)) as u8;
                pixel[2] = (blue + mul(pixel[2] as u32, rest)) as u8;
                pixel[3] = (alpha + mul(pixel[3] as u32, rest)) as u8;
            }
        }
    }
}

fn draw_text(canvas: &mut [u8], text: &str, x: i64, y: i64, size: i64, color: u32) {
    let scale = ((size + LINE / 2) / LINE).max(1);
    let mut pen_x = x;
    let mut pen_y = y;
    for &byte in text.as_bytes() {
        let code = byte as i64;
        if code == 10 {
            pen_x = x;
            pen_y += LINE * scale;
            continue;
        }
        if (128..192).contains(&code) {
            continue;
        }
        let glyph = if (32..=126).contains(&code) { code - 32 } else { 31 };
        for column in 0..5 {
            let bits = FONT5X7[(glyph * 5 + column) as usize] as i64;
            let mut row = 0;
            while row < 7 {
                if (bits >> row) & 1 == 0 {
                    row += 1;
                    continue;
                }
                let start = row;
                while row < 7 && (bits >> row) & 1 != 0 {
                    row += 1;
                }
                fill(canvas, pen_x + column * scale, pen_y + start * scale, scale, (row - start) * scale, color, false);
            }
        }
        pen_x += ADVANCE * scale;
    }
}

fn end_drawing(canvas: &[u8]) {
    let Some(path) = std::env::var_os("JET_FRAME_CAPTURE") else { return };
    if path.is_empty() {
        return;
    }
    let Ok(mut file) = std::fs::File::create(path) else { return };
    let header = format!("P7\nWIDTH {W}\nHEIGHT {H}\nDEPTH 4\nMAXVAL 255\nTUPLTYPE RGB_ALPHA\nENDHDR\n");
    if file.write_all(header.as_bytes()).is_ok() {
        let _ = file.write_all(canvas);
    }
}

fn main() {
    let palette = [rgba(0, 0, 0, 0), rgba(52, 101, 164, 255), rgba(78, 154, 6, 255), rgba(196, 160, 0, 255)];
    let sky = rgba(16, 20, 32, 255);
    let bar = rgba(0, 0, 0, 160);
    let white = rgba(255, 255, 255, 255);
    let gold = rgba(255, 220, 120, 200);
    let title = "JET RASTER";
    let (mut tiles, mut sprites, mut glyphs) = (0i64, 0i64, 0i64);
    let mut canvas = vec![0u8; (W * H * 4) as usize];
    for f in 0..FRAMES {
        fill(&mut canvas, 0, 0, W, H, sky, true);
        let scroll = f % 16;
        let base = f / 16;
        for ty in 0..12 {
            for tx in 0..21 {
                let p = ((tx + base) * 7 + ty * 5) % 4;
                if p == 0 {
                    continue;
                }
                fill(&mut canvas, tx * 16 - scroll, ty * 16 + 8, 15, 15, palette[p as usize], false);
                tiles += 1;
            }
        }
        for i in 0..48 {
            let x = (i * 41 + f * (1 + i % 4)) % 344 - 12;
            let y = (i * 29 + f * (1 + i % 3)) % 224 - 12;
            fill(&mut canvas, x, y, 12, 12, rgba((i * 53) % 256, (i * 97) % 256, (i * 31 + f) % 256, 180), false);
            sprites += 1;
        }
        fill(&mut canvas, 0, 0, W, 12, bar, false);
        let hud = format!("SCORE {} FRAME {}", (f * 7) % 100000, f);
        draw_text(&mut canvas, &hud, 4, 2, 10, white);
        draw_text(&mut canvas, title, 196, 176, 20, gold);
        glyphs += (hud.len() + title.len()) as i64;
        end_drawing(&canvas);
    }
    println!("frames={FRAMES} tiles={tiles} sprites={sprites} glyphs={glyphs}");
}
