#!/usr/bin/env node
// Deterministic generator for the build-system axis project (Nix peer).
//
// One medium project, two build systems. The program is the mid-size
// build-time workload (Tools/perf/build-time/midsize.mjs: 90 units folded into
// one checksum line), split into one source file per 10 units so a one-file
// edit is a real incremental change:
//   OUT/jet  a Jet package: package.jet, the build program @build.jet
//            (`fn build` registers one executable), run.jet, units_0..8.jet
//   OUT/nix  a flake: flake.nix (stdenv.mkDerivation over src/), flake.lock
//            pinning the repository's own nixpkgs, src/Makefile, src/main.c,
//            src/units.h, src/units_0..8.c
// Both artifacts print Tools/perf/build-time/midsize.out byte for byte.
//
// usage: node Tools/gauntlet/axes/build-system/generate.mjs OUT_DIR

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { MODULUS, UNITS, jetUnit, seed, unitConstants } from "../../../perf/build-time/midsize.mjs";

export const FILES = 9;
export const UNITS_PER_FILE = UNITS / FILES;
export const SYSTEM = "x86_64-linux";
const HEADER = "Build-system axis project (generated by Tools/gauntlet/axes/build-system/generate.mjs; do not edit).";
const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../../..");

const fileUnits = (file) => Array.from({ length: UNITS_PER_FILE }, (_, k) => file * UNITS_PER_FILE + k);
const unitNames = Array.from({ length: FILES }, (_, file) => `units_${file}`);

function cUnit(i) {
  const { c1, c2, c3, t1, t2, n } = unitConstants(i);
  return `/* Unit ${i}: state step, classification, and scoring. */
typedef struct {
    int64_t a;
    int64_t b;
    int64_t c;
} State${i};

enum { KIND${i}_LOW, KIND${i}_MID, KIND${i}_HIGH };

typedef struct {
    int tag;
    int64_t v;
} Kind${i};

static Kind${i} classify_${i}(int64_t x) {
    if (x < ${t1}) {
        return (Kind${i}){KIND${i}_LOW, x};
    }
    if (x < ${t2}) {
        return (Kind${i}){KIND${i}_MID, x - ${t1}};
    }
    return (Kind${i}){KIND${i}_HIGH, 0};
}

static int64_t score_${i}(Kind${i} kind) {
    switch (kind.tag) {
    case KIND${i}_LOW:
        return kind.v * ${c1} + 1;
    case KIND${i}_MID:
        return kind.v * ${c2} + 7;
    default:
        return ${c3};
    }
}

static State${i} step_${i}(State${i} s, int64_t x) {
    int64_t a = (s.a * ${c1} + x + 1) % ${MODULUS};
    int64_t b = (s.b + a * ${c2}) % ${MODULUS};
    int64_t c = (s.c + a + b * 3) % ${MODULUS};
    return (State${i}){a, b, c};
}

int64_t unit_${i}(int64_t seed) {
    State${i} s = {seed % ${MODULUS}, ${c2}, ${c3}};
    int64_t values[${n}];
    for (int64_t j = 0; j < ${n}; j++) {
        s = step_${i}(s, j);
        values[j] = score_${i}(classify_${i}(s.a % 1000));
    }
    int64_t total = 0;
    for (int64_t j = 0; j < ${n}; j++) {
        if (values[j] % 2 == 0) {
            total += values[j];
        } else {
            total += values[j] * 3;
        }
    }
    return (total + s.b + s.c) % ${MODULUS};
}
`;
}

function jetFiles() {
  const sources = ["run.jet", ...unitNames.map((name) => `${name}.jet`)];
  const folds = Array.from({ length: UNITS }, (_, i) => `    total = (total * 31 + unit_${i}(${seed(i)})) % ${MODULUS}`).join("\n");
  const files = {
    "package.jet": `// ${HEADER}\nname: "medium"\nversion: "0.1.0"\nedition: "2026"\n`,
    "@build.jet": `// ${HEADER}\nfn build(b: Build) {\n    app :: b.add_executable("medium", [${sources.map((s) => JSON.stringify(s)).join(", ")}], [])\n    b.default(app)\n}\n`,
    "run.jet": `// ${HEADER}\nfn run() {\n    total := 0\n${folds}\n    print("checksum {total}")\n}\n`,
  };
  unitNames.forEach((name, file) => {
    files[`${name}.jet`] = `// ${HEADER}\n${fileUnits(file).map(jetUnit).join("\n")}`;
  });
  return files;
}

function nixpkgsLock() {
  const lock = JSON.parse(fs.readFileSync(path.join(REPO, "flake.lock"), "utf8"));
  return lock.nodes[lock.nodes[lock.root].inputs.nixpkgs].locked;
}

function nixFiles() {
  const locked = nixpkgsLock();
  const { owner, repo, rev } = locked;
  const objects = ["main.o", ...unitNames.map((name) => `${name}.o`)].join(" ");
  const files = {
    "flake.nix": `# ${HEADER}
{
  inputs.nixpkgs.url = "github:${owner}/${repo}/${rev}";

  outputs =
    { self, nixpkgs }:
    let
      pkgs = nixpkgs.legacyPackages.${SYSTEM};
    in
    {
      packages.${SYSTEM}.default = pkgs.stdenv.mkDerivation {
        pname = "medium";
        version = "0.1.0";
        src = ./src;
        enableParallelBuilding = true;
        installPhase = "install -Dm755 medium $out/bin/medium";
      };
    };
}
`,
    "flake.lock": `${JSON.stringify(
      {
        nodes: {
          nixpkgs: { locked, original: { owner, repo, rev, type: locked.type } },
          root: { inputs: { nixpkgs: "nixpkgs" } },
        },
        root: "root",
        version: 7,
      },
      null,
      2,
    )}\n`,
    "src/Makefile": `# ${HEADER}\nOBJS = ${objects}\n\nmedium: $(OBJS)\n\t$(CC) -O1 -o $@ $(OBJS)\n\n%.o: %.c units.h\n\t$(CC) -O1 -c $<\n`,
    "src/units.h": `/* ${HEADER} */\n#include <stdint.h>\n\n${Array.from({ length: UNITS }, (_, i) => `int64_t unit_${i}(int64_t seed);`).join("\n")}\n`,
    "src/main.c": `/* ${HEADER} */\n#include <inttypes.h>\n#include <stdio.h>\n#include "units.h"\n\nint main(void) {\n    int64_t total = 0;\n${Array.from({ length: UNITS }, (_, i) => `    total = (total * 31 + unit_${i}(${seed(i)})) % ${MODULUS};`).join("\n")}\n    printf("checksum %" PRId64 "\\n", total);\n    return 0;\n}\n`,
  };
  unitNames.forEach((name, file) => {
    files[`src/${name}.c`] = `/* ${HEADER} */\n#include "units.h"\n\n${fileUnits(file).map(cUnit).join("\n")}`;
  });
  return files;
}

export function generate() {
  const out = {};
  for (const [name, text] of Object.entries(jetFiles())) out[`jet/${name}`] = text;
  for (const [name, text] of Object.entries(nixFiles())) out[`nix/${name}`] = text;
  return out;
}

// The file every one-file incremental sample edits, per build system.
export const EDIT_FILES = { jet: "jet/units_4.jet", nix: "nix/src/units_4.c" };

export function write(outDir) {
  for (const [name, text] of Object.entries(generate())) {
    const file = path.join(outDir, name);
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, text);
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = process.argv[2];
  if (!out) {
    console.error("usage: node Tools/gauntlet/axes/build-system/generate.mjs OUT_DIR");
    process.exit(64);
  }
  write(out);
}
