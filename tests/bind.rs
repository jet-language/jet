mod common;

use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

fn scratch(name: &str) -> PathBuf {
    let path = common::unique_tmp(&format!("jet-bind-{name}"));
    fs::create_dir_all(&path).unwrap();
    path
}

fn generated(
    format: &str,
    path: &str,
    input: &str,
    root: Option<&str>,
    command: &str,
) -> String {
    let dir = scratch(&format!("generated-{format}"));
    let input_path = dir.join(path);
    if let Some(parent) = input_path.parent().filter(|path| !path.as_os_str().is_empty()) {
        fs::create_dir_all(parent).unwrap();
    }
    fs::write(&input_path, input).unwrap();
    let source = run_public_data_bind(&dir, format, path, root, command);
    let _ = fs::remove_dir_all(dir);
    source
}

fn escape_provenance(value: &str) -> String {
    value
        .chars()
        .flat_map(|ch| match ch {
            '\\' => "\\\\".chars().collect::<Vec<_>>(),
            '\n' => "\\n".chars().collect(),
            '\r' => "\\r".chars().collect(),
            '\t' => "\\t".chars().collect(),
            ch if ch.is_control() || matches!(ch, '\u{2028}' | '\u{2029}') => {
                format!("\\u{:04x}", ch as u32).chars().collect()
            }
            ch => vec![ch],
        })
        .collect()
}

fn run_public_data_bind(
    dir: &Path,
    format: &str,
    input_path: &str,
    root: Option<&str>,
    command: &str,
) -> String {
    let mut args = vec![
        "inspect".to_string(),
        "bind".to_string(),
        format.to_string(),
        input_path.to_string(),
    ];
    if let Some(root) = root {
        args.extend(["--type".to_string(), root.to_string()]);
    }
    let output = Command::new(env!("CARGO_BIN_EXE_jet"))
        .args(&args)
        .current_dir(dir)
        .env("NO_COLOR", "1")
        .output()
        .unwrap();
    assert_success(&output);
    let stdout = String::from_utf8_lossy(&output.stdout);
    let output_path = stdout
        .lines()
        .find_map(|line| line.split_once(" → ").map(|(_, path)| path.trim()))
        .unwrap_or_else(|| panic!("public `jet inspect bind` did not report an output path:\n{stdout}"));
    let source = fs::read_to_string(dir.join(output_path)).unwrap();
    let expected_provenance = format!("// generated by: {}", escape_provenance(command));
    assert!(
        source.contains(&expected_provenance),
        "public `jet inspect bind` changed provenance:\n{source}"
    );
    source
}

fn assert_success(output: &std::process::Output) {
    assert!(
        output.status.success(),
        "status={:?}\nstderr={}",
        output.status.code(),
        String::from_utf8_lossy(&output.stderr)
    );
}

/// Run generated source as part of a real project. The typed field reads make
/// a parser-only or fallback implementation fail before either execution tier
/// can report the expected output.
fn assert_generated_project(
    name: &str,
    format: &str,
    input_path: &str,
    input: &str,
    root: &str,
    command: &str,
    program: &str,
    expected_stdout: &str,
    source_markers: &[&str],
) {
    let dir = scratch(&format!("project-{name}"));
    let input_file = dir.join(input_path);
    if let Some(parent) = input_file.parent().filter(|path| !path.as_os_str().is_empty()) {
        fs::create_dir_all(parent).unwrap();
    }
    fs::write(&input_file, input).unwrap();
    let generated = run_public_data_bind(&dir, format, input_path, Some(root), command);
    for marker in source_markers {
        assert!(
            generated.contains(marker),
            "{format} generated source lost required schema marker {marker:?}:\n{generated}"
        );
    }
    assert_generated_source_parses(&generated);
    assert!(
        !generated.contains("DataTree"),
        "{format} project would exercise the dynamic fallback instead of typed generated fields:\n{generated}"
    );

    let main_path = dir.join("main.jet");
    let project_source = format!("{generated}\n{program}");
    fs::write(&main_path, &project_source).unwrap();
    let shown = main_path.to_string_lossy().into_owned();
    let compiled = jet::compile_with_path(&project_source, &shown).unwrap_or_else(|diagnostics| {
        panic!(
            "semantic analysis rejected generated {format} project:\n{}",
            jet::render_diagnostics(&shown, &project_source, &diagnostics)
        )
    });
    let generated_rust_type = jet::Syntax::generated_name(root);
    assert!(
        compiled
            .rust
            .contains(&format!("pub struct {generated_rust_type}")),
        "codegen omitted generated {root} instead of using a fallback project:\n{}",
        compiled.rust
    );

    let rust_path = dir.join("main.rs");
    let binary_path = dir.join("main");
    fs::write(&rust_path, &compiled.rust).unwrap();
    let aot = Command::new("rustc")
        .args(["--edition", "2021"])
        .arg(&rust_path)
        .arg("-o")
        .arg(&binary_path)
        .output()
        .unwrap();
    assert_success(&aot);
    let aot_run = Command::new(&binary_path).current_dir(&dir).output().unwrap();
    assert_success(&aot_run);
    assert_eq!(
        String::from_utf8_lossy(&aot_run.stdout),
        expected_stdout,
        "AOT output did not use generated {format} fields"
    );

    let jit_run = Command::new(env!("CARGO_BIN_EXE_jet"))
        .args(["run", "main.jet"])
        .current_dir(&dir)
        .env("JET_CACHE_DIR", dir.join("run-cache"))
        .env("NO_COLOR", "1")
        .output()
        .unwrap();
    assert_success(&jit_run);
    assert_eq!(
        String::from_utf8_lossy(&jit_run.stdout),
        expected_stdout,
        "default `jet run` output did not use generated {format} fields"
    );
    let _ = fs::remove_dir_all(dir);
}

fn assert_generated_source_parses(source: &str) {
    let (tokens, diagnostics) = jet::Lexer::lex_generated(source);
    assert!(diagnostics.is_empty(), "generated source lexed with diagnostics: {diagnostics:#?}");
    assert!(
        jet::Parser::parse(&tokens).is_ok(),
        "generated source did not parse:\n{source}"
    );
}

fn check_cli_snapshot(name: &str, actual: &str) {
    let path = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("tests/cli")
        .join(name);
    if std::env::var("UPDATE_EXPECT").is_ok() {
        fs::write(&path, actual).unwrap();
        return;
    }
    let expected = fs::read_to_string(&path).unwrap_or_else(|_| {
        panic!(
            "missing snapshot {}; run UPDATE_EXPECT=1 cargo test",
            path.display()
        )
    });
    assert_eq!(actual, expected, "snapshot mismatch for {}", name);
}

fn scrub_cli_path(output: &str, file: &Path) -> String {
    output.replace(&file.display().to_string(), "BAD.jet")
}

