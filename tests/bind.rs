#[test]
fn retired_top_level_bind_forms_teach_the_grouped_route() {
    let dir = scratch("retired-bind");
    let cases = vec![
        vec!["bind", "missing.h"],
        vec!["--json", "bind", "missing.h"],
        vec!["-v", "bind", "missing.h"],
        vec!["--color=never", "bind", "missing.h"],
    ];
    for args in cases {
        let output = Command::new(env!("CARGO_BIN_EXE_jet"))
            .args(args)
            .current_dir(&dir)
            .env("NO_COLOR", "1")
            .output()
            .unwrap();
        let rendered = format!(
            "{}\n{}",
            String::from_utf8_lossy(&output.stdout),
            String::from_utf8_lossy(&output.stderr)
        );
        assert!(!output.status.success(), "retired bind unexpectedly succeeded: {rendered}");
        assert!(rendered.contains("E2101"), "retired bind lost its teaching diagnostic: {rendered}");
        assert!(rendered.contains("inspect bind"), "retired bind lost its canonical fix: {rendered}");
        assert!(!rendered.contains("jet bind"), "retired bind kept a top-level alias: {rendered}");
        assert!(!rendered.contains("E3208"), "retired bind reached the binder: {rendered}");
    }
    let _ = fs::remove_dir_all(dir);
}

