#[test]
fn xml_bind_resolves_namespaces_omits_declarations_and_keeps_collisions() {
    let input = r#"<root xmlns="urn:root" xmlns:a="urn:one" xmlns:b="urn_one" a:id="left" b:id="right" id="plain" xml:lang="en"><a:item>one</a:item><b:item>two</b:item><a:record><value>left</value></a:record><b:record><value>right</value></b:record><nested xmlns="urn:nested"><leaf>three</leaf></nested></root>"#;
    let command = "jet inspect bind xml namespaced.xml --type Root";
    let first = generated("xml", "namespaced.xml", input, Some("Root"), command);
    let second = generated("xml", "namespaced.xml", input, Some("Root"), command);
    assert_eq!(first, second, "XML namespace naming must be deterministic");
    assert!(first.contains("generated by: jet inspect bind xml namespaced.xml --type Root"));
    assert!(first.contains("input: namespaced.xml"));
    assert!(first.contains(&format!(
        "sha256: {}",
        jet::SHA256::sha256_hex(input.as_bytes())
    )));
    assert!(!first.contains("xmlns"), "namespace declarations are not wire fields");

    let field_marker = |wire: &str, name: &str, ty: &str| {
        let escaped = format!("{wire:?}").replace('{', "{{").replace('}', "}}");
        format!("#Rename({escaped}) {name}: {ty}")
    };
    let id_base = jet::Syntax::sanitize_generated_name(
        "{urn:one}id",
        jet::Syntax::NameCase::Snake,
        "field",
    );
    assert_eq!(
        id_base,
        jet::Syntax::sanitize_generated_name(
            "{urn_one}id",
            jet::Syntax::NameCase::Snake,
            "field",
        )
    );
    assert!(first.contains(&field_marker("@id", "id", "String")));
    assert!(first.contains(&field_marker("@{urn:one}id", &id_base, "String")));
    assert!(first.contains(&field_marker("@{urn_one}id", &format!("{id_base}_2"), "String")));
    assert!(first.contains(&field_marker(
        "@{http://www.w3.org/XML/1998/namespace}lang",
        &jet::Syntax::sanitize_generated_name(
            "@{http://www.w3.org/XML/1998/namespace}lang",
            jet::Syntax::NameCase::Snake,
            "field",
        ),
        "String",
    )));

    let item_base = jet::Syntax::sanitize_generated_name(
        "{urn:one}item",
        jet::Syntax::NameCase::Snake,
        "field",
    );
    assert_eq!(
        item_base,
        jet::Syntax::sanitize_generated_name(
            "{urn_one}item",
            jet::Syntax::NameCase::Snake,
            "field",
        )
    );
    assert!(first.contains(&field_marker("{urn:one}item", &item_base, "String")));
    assert!(first.contains(&field_marker("{urn_one}item", &format!("{item_base}_2"), "String")));
    let record_base = jet::Syntax::sanitize_generated_name(
        &format!(
            "Root{}",
            jet::Syntax::sanitize_generated_name(
                "{urn:one}record",
                jet::Syntax::NameCase::Pascal,
                "Schema",
            )
        ),
        jet::Syntax::NameCase::Pascal,
        "Schema",
    );
    assert_eq!(
        record_base,
        jet::Syntax::sanitize_generated_name(
            &format!(
                "Root{}",
                jet::Syntax::sanitize_generated_name(
                    "{urn_one}record",
                    jet::Syntax::NameCase::Pascal,
                    "Schema",
                )
            ),
            jet::Syntax::NameCase::Pascal,
            "Schema",
        )
    );
    let record_field = jet::Syntax::sanitize_generated_name(
        "{urn:one}record",
        jet::Syntax::NameCase::Snake,
        "field",
    );
    assert!(first.contains(&field_marker(
        "{urn:one}record",
        &record_field,
        &record_base,
    )));
    assert!(first.contains(&field_marker(
        "{urn_one}record",
        &format!("{record_field}_2"),
        &format!("{record_base}_2"),
    )));
    assert!(first.contains(&format!("struct {record_base} {{")));
    assert!(first.contains(&format!("struct {record_base}_2 {{")));
    let nested_leaf = jet::Syntax::sanitize_generated_name(
        "{urn:nested}leaf",
        jet::Syntax::NameCase::Snake,
        "field",
    );
    assert!(first.contains(&field_marker(
        "{urn:nested}leaf",
        &nested_leaf,
        "String",
    )));
    assert_generated_source_parses(&first);
}

