#[test]
fn data_bind_provenance_is_hashed_and_stable() {
    let input = "{\"name\":\"jet\",\"count\":2}";
    let first = generated(
        "json",
        "fixtures/stable.json",
        input,
        Some("Stable"),
        "jet bind json fixtures/stable.json --type Stable",
    );
    let second = generated(
        "json",
        "fixtures/stable.json",
        input,
        Some("Stable"),
        "jet bind json fixtures/stable.json --type Stable",
    );
    assert_eq!(first, second);
    let hash = jet::SHA256::sha256_hex(input.as_bytes());
    assert!(first.contains("input: fixtures/stable.json"));
    assert!(first.contains(&format!("sha256: {hash}")));
    assert!(first.contains("generated by: jet bind json fixtures/stable.json --type Stable"));
    assert!(first.contains("format: json"));
    assert!(first.contains("inference: JSON object fields become #Codable fields"));

    let changed = generated(
        "json",
        "fixtures/stable.json",
        "{\"name\":\"jet\",\"count\":3}",
        Some("Stable"),
        "jet bind json fixtures/stable.json --type Stable",
    );
    assert_ne!(first, changed);
}

#[test]
fn public_cli_covers_each_data_format_parse_hash_and_idempotence() {
    let dir = scratch("all-formats");
    let cases = [
        (
            "json",
            "repo.json",
            r#"{"name":"jet","count":9007199254740993,"scale":1e9999}"#,
            "Repo",
        ),
        (
            "csv",
            "people.csv",
            "name,age\nAda,36\nLin,37\n",
            "Person",
        ),
        (
            "sql",
            "schema.sql",
            "CREATE TABLE users (id INTEGER PRIMARY KEY, name VARCHAR(32) NOT NULL, created TIMESTAMP(0));",
            "Users",
        ),
        (
            "xml",
            "catalog.xml",
            "<?xml version=\"1.0\" encoding=\"UTF-8\"?><catalog><book id=\"1\"/></catalog>",
            "Catalog",
        ),
        (
            "proto",
            "repo.proto",
            "syntax = \"proto3\"; message Repo { string name = 1; }",
            "Repo",
        ),
    ];
    for (format, filename, input, root) in cases {
        let input_path = dir.join(filename);
        fs::write(&input_path, input).unwrap();
        let input_text = input_path.to_str().unwrap();
        let args = ["bind", format, input_text, "--type", root];
        let first = Command::new(env!("CARGO_BIN_EXE_jet"))
            .args(args)
            .current_dir(&dir)
            .env("NO_COLOR", "1")
            .output()
            .unwrap();
        assert_success(first);
        let stem = filename.rsplit_once('.').map(|(stem, _)| stem).unwrap();
        let output_path = dir.join("bindings").join(format!("{stem}.jet"));
        let before = fs::read_to_string(&output_path).unwrap();
        assert!(before.contains("#Codable"));
        assert!(before.contains(&format!("sha256: {}", jet::SHA256::sha256_hex(input.as_bytes()))));
        assert_generated_source_parses(&before);

        let second = Command::new(env!("CARGO_BIN_EXE_jet"))
            .args(args)
            .current_dir(&dir)
            .env("NO_COLOR", "1")
            .output()
            .unwrap();
        assert_success(second);
        assert_eq!(before, fs::read_to_string(&output_path).unwrap());
    }

    let malformed = [
        ("json", "bad.json", "{"),
        ("csv", "bad.csv", "a,a\n1,2\n"),
        ("sql", "bad.sql", "CREATE TABLE x (id UNKNOWN);"),
        ("xml", "bad.xml", "<a attr=\"&bad;\"/>"),
        ("proto", "bad.proto", "message A { string x = 19000; }"),
    ];
    for (format, filename, input) in malformed {
        let path = dir.join(filename);
        fs::write(&path, input).unwrap();
        let output = Command::new(env!("CARGO_BIN_EXE_jet"))
            .args(["bind", format, path.to_str().unwrap(), "--type", "Bad"])
            .current_dir(&dir)
            .env("NO_COLOR", "1")
            .output()
            .unwrap();
        assert_eq!(output.status.code(), Some(1));
        let stderr = String::from_utf8_lossy(&output.stderr);
        assert!(stderr.contains("Error [E3208]:"), "{format} missing E3208: {stderr}");
        assert!(stderr.contains("Why:") && stderr.contains("Fix:"), "{format}: {stderr}");
    }
    let _ = fs::remove_dir_all(dir);
}

#[test]
fn data_bind_cli_writes_visible_output_and_regeneration_diff() {
    let dir = scratch("cli");
    let input = dir.join("records.json");
    fs::write(&input, "{\"name\":\"first\",\"count\":1}").unwrap();
    let input_text = input.to_str().unwrap();

    let first = Command::new(env!("CARGO_BIN_EXE_jet"))
        .args(["bind", "json", input_text, "--type", "Record"])
        .current_dir(&dir)
        .output()
        .unwrap();
    assert_success(first);
    let default_output = dir.join("bindings/records.jet");
    assert!(default_output.is_file());
    let before = fs::read_to_string(&default_output).unwrap();
    assert!(before.contains("#Codable"));
    assert!(before.contains("struct Record"));
    assert!(before.contains(input_text));

    fs::write(&input, "{\"name\":\"second\",\"count\":2,\"active\":true}").unwrap();
    let stale = fs::read_to_string(&default_output).unwrap();
    assert_eq!(before, stale);

    let regenerated = Command::new(env!("CARGO_BIN_EXE_jet"))
        .args(["bind", "json", input_text, "--type", "Record"])
        .current_dir(&dir)
        .output()
        .unwrap();
    assert_success(regenerated);
    let regenerated_output = fs::read_to_string(&default_output).unwrap();
    assert_ne!(before, regenerated_output);
    assert!(regenerated_output.contains("active: Bool"));

    let explicit = dir.join("generated/record.jet");
    let explicit_text = explicit.to_str().unwrap();
    let second = Command::new(env!("CARGO_BIN_EXE_jet"))
        .args([
            "bind",
            "json",
            input_text,
            "--type",
            "Record",
            "-o",
            explicit_text,
        ])
        .current_dir(&dir)
        .output()
        .unwrap();
    assert_success(second);
    let after = fs::read_to_string(&explicit).unwrap();
    assert_ne!(before, after);
    assert!(after.contains("active: Bool"));
    assert!(after.contains(explicit_text));
    assert!(Path::new(explicit_text).is_file());

    let _ = fs::remove_dir_all(dir);
}
