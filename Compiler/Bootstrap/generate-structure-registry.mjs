#!/usr/bin/env node
// Generate the CLI's structure registry view from the same declaration sources
// Rust Registry/CoreModuleExports read. No hand-maintained mirror catalog.
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { factDeclarations } from './fact-declarations.mjs';
import { parseCoreSource } from '../../Tools/agent/check-core-surface-ledger.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const corePath = 'crates/jet-codegen/src/Prelude/Core.jet';
const factsPath = 'crates/jet-codegen/src/Prelude/Facts.jet';
const core = await readFile(resolve(root, corePath), 'utf8');
const facts = await readFile(resolve(root, factsPath), 'utf8');
const quote = value => JSON.stringify(value).replaceAll('{', '{{').replaceAll('}', '}}');
const strings = values => `[String]{${values.map(quote).join(', ')}}`;
const declarations = parseCoreSource(core, root);
const bootstrap = declarations.bootstraps.map(step =>
  `    JetCLICoreBootstrap{name: ${quote(step.name)}, dependencies: ${strings(step.dependencies)}},`);
const roots = declarations.rootTypes;
const modules = declarations.modules.map(module => {
  const types = module.types.map(type => {
    const kind = type.genericArity
      ? `CoreLeafKind.Generic{arity: ${type.genericArity}}`
      : type.variants.length
        ? `CoreLeafKind.Enum{variants: ${strings(type.variants)}}`
        : type.kind === 'crypto_nominal' ? 'CoreLeafKind.CryptoNominal' : 'CoreLeafKind.Plain';
    return `CoreModuleTypeExport{name: ${quote(type.name)}, kind: ${kind}}`;
  });
  return `    CoreModuleDeclaration{module_name: ${quote(module.module)}, members: ${strings(module.members)}, type_exports: [CoreModuleTypeExport]{${types.join(', ')}}, dependencies: ${strings(module.dependencies)}},`;
});
const rows = [];
for (const row of factDeclarations(facts)) {
  if (!row.name.startsWith('Structure.')) continue;
  rows.push(`    JetCLIStructureRegistryRow{name: ${quote(row.name)}, safe_direction: ${quote(row.safe)}, gates: ${strings(row.gates)}},`);
}
if (!roots || !bootstrap.length || !modules.length || !rows.length) throw new Error('declaration source has an empty required table');
const digest = createHash('sha256').update(core).update(facts).digest('hex');
const output = `// Generated by Compiler/Bootstrap/generate-structure-registry.mjs; do not edit.\n// Sources: ${corePath}; ${factsPath}\n// Source SHA-256: ${digest}\nuse jet_foundation.[CoreLeafKind, CoreModuleTypeExport, CoreModuleDeclaration]\n\nstruct JetCLICoreBootstrap {\n    name: String\n    dependencies: [String]\n}\nstruct JetCLIStructureRegistryRow {\n    name: String\n    safe_direction: String\n    gates: [String]\n}\n\nJET_CLI_STRUCTURE_ROWS :: [JetCLIStructureRegistryRow]{\n${rows.join('\n')}\n}\nJET_CLI_CORE_BOOTSTRAP :: [JetCLICoreBootstrap]{\n${bootstrap.join('\n')}\n}\nJET_CLI_CORE_ROOT_TYPES :: ${strings(roots)}\nJET_CLI_CORE_DECLARATIONS :: [CoreModuleDeclaration]{\n${modules.join('\n')}\n}\n`;
const destination = resolve(root, 'Compiler/JetCli/Source/Cli/StructureRegistry.jet');
if (process.argv.includes('--check')) {
  if (await readFile(destination, 'utf8') !== output) throw new Error('StructureRegistry.jet is stale');
} else {
  await writeFile(destination, output);
}
