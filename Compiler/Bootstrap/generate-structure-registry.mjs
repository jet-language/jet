#!/usr/bin/env node
// Generate the CLI's structure registry view from the same declaration sources
// Rust Registry/CoreModuleExports read. No hand-maintained mirror catalog.
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const corePath = 'crates/jet-codegen/src/Prelude/Core.jet';
const factsPath = 'crates/jet-codegen/src/Prelude/Facts.jet';
const core = await readFile(resolve(root, corePath), 'utf8');
const facts = await readFile(resolve(root, factsPath), 'utf8');
const quote = value => JSON.stringify(value).replaceAll('{', '{{').replaceAll('}', '}}');
const strings = values => `[String]{${values.map(quote).join(', ')}}`;
const names = text => text.split(',').map(value => value.trim()).filter(Boolean);
const bootstrap = [];
const modules = [];
let roots;
for (const raw of core.split('\n')) {
  const line = raw.trim();
  if (!line || line.startsWith('//')) continue;
  if (line.startsWith('bootstrap ')) {
    const match = line.match(/^bootstrap (\w+) depends_on \[([^\]]*)\]$/);
    if (!match) throw new Error(`invalid bootstrap declaration: ${line}`);
    bootstrap.push(`    JetCLICoreBootstrap{name: ${quote(match[1])}, dependencies: ${strings(names(match[2]))}},`);
  } else if (line.startsWith('root_types ')) {
    const match = line.match(/^root_types \{([^}]*)\}$/);
    if (!match || roots) throw new Error(`invalid root_types declaration: ${line}`);
    roots = names(match[1]);
  } else if (line.startsWith('module ')) {
    const match = line.match(/^module (\S+) exports \{([^}]*)\}(?: types \{([^}]*)\})? depends_on \[([^\]]*)\]$/);
    if (!match) throw new Error(`invalid core module declaration: ${line}`);
    const types = [];
    for (const item of names(match[3] ?? '')) {
      const type = item.match(/^(\w+):(plain|crypto_nominal|generic)(?:\(([^)]*)\))?$/);
      if (!type) throw new Error(`invalid type export: ${item}`);
      let kind;
      if (type[2] === 'plain') kind = type[3] === undefined ? 'CoreLeafKind.Plain' : `CoreLeafKind.Enum{variants: ${strings(type[3].split('|'))}}`;
      else if (type[2] === 'crypto_nominal') kind = 'CoreLeafKind.CryptoNominal';
      else {
        if (!/^\d+$/.test(type[3] ?? '')) throw new Error(`invalid generic arity: ${item}`);
        kind = `CoreLeafKind.Generic{arity: ${type[3]}}`;
      }
      types.push(`CoreModuleTypeExport{name: ${quote(type[1])}, kind: ${kind}}`);
    }
    modules.push(`    CoreModuleDeclaration{module_name: ${quote(match[1])}, members: ${strings(names(match[2]))}, type_exports: [CoreModuleTypeExport]{${types.join(', ')}}, dependencies: ${strings(names(match[4]))}},`);
  }
}
const rows = [];
for (const raw of facts.split('\n')) {
  if (!raw.startsWith('fact ') || !raw.includes('$name: "Structure.')) continue;
  const match = raw.match(/^fact \w+\(\$name: "(Structure\.[^"]+)", \$holds: \.Build, \$safe: \.(\w+), \$gates: \[([^\]]*)\], \$decision: "([^"]+)"\)$/);
  if (!match) throw new Error(`invalid structure fact declaration: ${raw}`);
  const gates = JSON.parse(`[${match[3]}]`);
  rows.push(`    JetCLIStructureRegistryRow{name: ${quote(match[1])}, safe_direction: ${quote(match[2].toLowerCase())}, gates: ${strings(gates)}, decision: ${quote(match[4])}},`);
}
if (!roots || !bootstrap.length || !modules.length || !rows.length) throw new Error('declaration source has an empty required table');
const digest = createHash('sha256').update(core).update(facts).digest('hex');
const output = `// Generated by Compiler/Bootstrap/generate-structure-registry.mjs; do not edit.\n// Sources: ${corePath}; ${factsPath}\n// Source SHA-256: ${digest}\nuse jet_foundation.[CoreLeafKind, CoreModuleTypeExport, CoreModuleDeclaration]\n\npub struct JetCLICoreBootstrap {\n    pub name: String\n    pub dependencies: [String]\n}\npub struct JetCLIStructureRegistryRow {\n    pub name: String\n    pub safe_direction: String\n    pub gates: [String]\n    pub decision: String\n}\n\npub JET_CLI_STRUCTURE_ROWS :: [JetCLIStructureRegistryRow]{\n${rows.join('\n')}\n}\npub JET_CLI_CORE_BOOTSTRAP :: [JetCLICoreBootstrap]{\n${bootstrap.join('\n')}\n}\npub JET_CLI_CORE_ROOT_TYPES :: ${strings(roots)}\npub JET_CLI_CORE_DECLARATIONS :: [CoreModuleDeclaration]{\n${modules.join('\n')}\n}\n`;
const destination = resolve(root, 'Compiler/JetCli/Source/Cli/StructureRegistry.jet');
if (process.argv.includes('--check')) {
  if (await readFile(destination, 'utf8') !== output) throw new Error('StructureRegistry.jet is stale');
} else {
  await writeFile(destination, output);
}
