#!/usr/bin/env node
// Embed the exact canonical built-in derive and error declarations in the
// self-hosted compiler. The Prelude files remain the only source; JetSema
// parses their embedded text through the ordinary/generated parser.
// usage: node Compiler/Bootstrap/generate-prelude-derives.mjs [--check]
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const bootstrapDir = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(bootstrapDir, "../..");
const sourceDisplayPath = "crates/jet-codegen/src/Prelude/Derives.jet";
const sourcePath = resolve(repoRoot, sourceDisplayPath);
const errorDisplayPath = "crates/jet-codegen/src/Prelude/Errors.jet";
const errorPath = resolve(repoRoot, errorDisplayPath);
const outputPath = resolve(repoRoot, "Compiler/JetSema/Source/Sema/Registration/PreludeDerives.jet");

function jetStringLiteral(value) {
  let literal = '"';
  for (const character of value) {
    const codepoint = character.codePointAt(0);
    if (codepoint < 0x20 && character !== "\n" && character !== "\t") {
      throw new Error(`prelude-derive-generator: control character U+${codepoint.toString(16)} in ${sourceDisplayPath}`);
    }
    if (character === "\\") literal += "\\\\";
    else if (character === '"') literal += '\\"';
    else if (character === "\n") literal += "\\n";
    else if (character === "\t") literal += "\\t";
    else if (character === "{") literal += "{{";
    else if (character === "}") literal += "}}";
    else literal += character;
  }
  return `${literal}"`;
}

const source = await readFile(sourcePath, "utf8");
const sourceHash = createHash("sha256").update(source).digest("hex");
const errorSource = await readFile(errorPath, "utf8");
const errorHash = createHash("sha256").update(errorSource).digest("hex");
const output = [
  "// BEGIN GENERATED PRELUDE DERIVE SOURCE",
  `// Source: ${sourceDisplayPath}`,
  `// Source SHA-256: ${sourceHash}`,
  "// This file is generated by Compiler/Bootstrap/generate-prelude-derives.mjs; do not edit.",
  "SEMA_PRELUDE_DERIVE_SOURCE_PATH :: prep { \"jet:canonical-prelude/Prelude/Derives.jet\" }",
  `SEMA_PRELUDE_DERIVE_SOURCE :: prep { ${jetStringLiteral(source)} }`,
  "// END GENERATED PRELUDE DERIVE SOURCE",
  "",
  "// BEGIN GENERATED PRELUDE ERROR SOURCE",
  `// Source: ${errorDisplayPath}`,
  `// Source SHA-256: ${errorHash}`,
  "// This file is generated by Compiler/Bootstrap/generate-prelude-derives.mjs; do not edit.",
  "SEMA_PRELUDE_ERROR_SOURCE_PATH :: prep { \"jet:canonical-prelude/Prelude/Errors.jet\" }",
  `SEMA_PRELUDE_ERROR_SOURCE :: prep { ${jetStringLiteral(errorSource)} }`,
  "// END GENERATED PRELUDE ERROR SOURCE",
  "",
].join("\n");

if (process.argv.includes("--check")) {
  const current = await readFile(outputPath, "utf8").catch(() => "");
  if (current !== output) {
    console.error(`${outputPath.replace(`${repoRoot}/`, "")} is stale; run node Compiler/Bootstrap/generate-prelude-derives.mjs`);
    process.exit(1);
  }
  console.log(`prelude derive/error sources are current (${sourceHash}/${errorHash})`);
} else {
  await writeFile(outputPath, output, "utf8");
  console.log(`generated ${outputPath.replace(`${repoRoot}/`, "")} (derive ${sourceHash}, error ${errorHash})`);
}

const markerDisplayPath = "crates/jet-codegen/src/Prelude/Markers.jet";
const markerPath = resolve(repoRoot, markerDisplayPath);
const markerOutputPath = resolve(repoRoot, "Compiler/JetSema/Source/Sema/Registration/PreludeMarkers.jet");
const markerSource = await readFile(markerPath, "utf8");
const markerHash = createHash("sha256").update(markerSource).digest("hex");
const markerOutput = [
  "// BEGIN GENERATED PRELUDE MARKER SOURCE",
  `// Source: ${markerDisplayPath}`,
  `// Source SHA-256: ${markerHash}`,
  "// This file is generated by Compiler/Bootstrap/generate-prelude-derives.mjs; do not edit.",
  `SEMA_PRELUDE_MARKER_SOURCE :: prep { ${jetStringLiteral(markerSource)} }`,
  "// END GENERATED PRELUDE MARKER SOURCE",
  "",
].join("\n");
if (process.argv.includes("--check")) {
  const current = await readFile(markerOutputPath, "utf8").catch(() => "");
  if (current !== markerOutput) {
    console.error(`${markerOutputPath.replace(`${repoRoot}/`, "")} is stale; run node Compiler/Bootstrap/generate-prelude-derives.mjs`);
    process.exit(1);
  }
  console.log(`prelude marker source is current (${markerHash})`);
} else {
  await writeFile(markerOutputPath, markerOutput, "utf8");
  console.log(`generated ${markerOutputPath.replace(`${repoRoot}/`, "")} (source ${markerHash})`);
}
