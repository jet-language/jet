#!/usr/bin/env node
// Generate the Jet CLI's view of the one native C compiler policy.
// `Compiler/JetCli/Assets/native-c-policy.tsv` stays the one source; this
// writes its rows as Jet constants, and Tools/packaging/native-c-compiler.mjs
// reads the same file through readNativeCPolicy.
// usage: node Compiler/Bootstrap/generate-native-c-policy.mjs [--check]
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { nativeCPolicyPath, parseNativeCPolicy } from "../../Tools/packaging/native-c-compiler.mjs";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const sourceDisplayPath = nativeCPolicyPath.replace(`${repoRoot}/`, "");
const outputPath = resolve(repoRoot, "Compiler/JetCli/Source/Cli/NativeCPolicy.jet");

function jetList(values) {
  for (const value of values) {
    if (!/^[\x21-\x7e]+$/u.test(value) || /["\\{}]/u.test(value)) {
      throw new Error(`native-c-policy-generator: ${sourceDisplayPath} value ${JSON.stringify(value)} is not a plain printable token`);
    }
  }
  return `[String]{${values.map(value => `"${value}"`).join(", ")}}`;
}

const source = await readFile(nativeCPolicyPath, "utf8");
const policy = parseNativeCPolicy(source);
const sourceHash = createHash("sha256").update(source).digest("hex");
const output = [
  "// BEGIN GENERATED NATIVE C POLICY",
  `// Source: ${sourceDisplayPath}`,
  `// Source SHA-256: ${sourceHash}`,
  "// This file is generated by Compiler/Bootstrap/generate-native-c-policy.mjs; do not edit.",
  "// Flags appended after every native C compiler invocation's own arguments.",
  `JET_CLI_NATIVE_C_FLAGS :: prep { ${jetList(policy.flags)} }`,
  "",
  "// Nix cc-wrapper features removed from the child's NIX_HARDENING_ENABLE.",
  `JET_CLI_NATIVE_C_HARDENING_REMOVED :: prep { ${jetList(policy.hardeningRemoved)} }`,
  "// END GENERATED NATIVE C POLICY",
  "",
].join("\n");

if (process.argv.includes("--check")) {
  const current = await readFile(outputPath, "utf8").catch(() => "");
  if (current !== output) {
    console.error(`${outputPath.replace(`${repoRoot}/`, "")} is stale; run node Compiler/Bootstrap/generate-native-c-policy.mjs`);
    process.exit(1);
  }
  console.log(`native C policy is current (${sourceHash})`);
} else {
  await writeFile(outputPath, output, "utf8");
  console.log(`generated ${outputPath.replace(`${repoRoot}/`, "")} (source ${sourceHash})`);
}
