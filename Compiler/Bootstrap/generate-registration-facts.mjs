#!/usr/bin/env node
// Generate the Foundation fact projection from the canonical Prelude facts.
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { factDeclarations } from './fact-declarations.mjs';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const sourcePath = 'crates/jet-codegen/src/Prelude/Facts.jet';
const source = await readFile(resolve(root, sourcePath), 'utf8');
const quote = value => JSON.stringify(value).replaceAll('{', '{{').replaceAll('}', '}}');
const strings = values => `[String]{${values.map(quote).join(', ')}}`;
const rows = factDeclarations(source).map(row => `    RegistrationFactRow{name: ${quote(row.name)}, target: RegistrationFactTarget.${row.target}, identity_bearing: ${row.identity}, safe_direction: ${quote(row.safe)}, gates: ${strings(row.gates)}, published_by: ${row.publishedBy === null ? 'None' : `Val(${quote(row.publishedBy)})`}, decision: ${quote(row.decision)}},`);
const digest = createHash('sha256').update(source).digest('hex');
const output = `// Generated by Compiler/Bootstrap/generate-registration-facts.mjs; do not edit.\n// Source: ${sourcePath}\n// Source SHA-256: ${digest}\n// FactReads02.jet/Registry.rs: one declaration projection, not another census.\npub enum RegistrationFactTarget { Value Scope Build }\npub struct RegistrationFactRow {\n    pub name: String\n    pub target: RegistrationFactTarget\n    pub identity_bearing: Bool\n    pub safe_direction: String\n    pub gates: [String]\n    pub published_by: String?\n    pub decision: String\n}\npub REGISTRATION_FACT_ROWS :: [RegistrationFactRow]{\n${rows.join('\n')}\n}\n`;
const destination = resolve(root, 'Compiler/JetFoundation/Source/Registry/RegistrationFacts.jet');
if (process.argv.includes('--check')) {
  if (await readFile(destination, 'utf8') !== output) throw new Error('RegistrationFacts.jet is stale');
} else {
  await writeFile(destination, output);
}
