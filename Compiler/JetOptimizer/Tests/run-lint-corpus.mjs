#!/usr/bin/env node
// MIR Lint over the complete real-program corpus (#4619 criterion 3): every
// native checked `.mird` in <out>/lower/<case>.mird goes through every MIR Lint
// rule. Checked MIR is well-formed by contract, so every finding is a lint
// false positive or a compiler defect; the gate is zero findings.
//
// The unit (<out>/lint/unit.jet) holds the Foundation items the MIR schema
// names, MIR.jet, Lint.jet, the `.mird` line reader of
// Compiler/JetBackend/Tests/GoldenLower.jet, the decoder mir-debug.mjs
// generates and Tests/LintCorpus.jet. Each process (`jet run unit.jet`, at
// most JET_LINT_BATCH cases, default 25; memory cap JET_LINT_MEM, default
// 4G) lints its cases in order and prints one line per finished case; a crash
// blames the first unfinished case and a fresh process takes the rest.
//
// Verdicts: clean, findings (the detail names the first one), lint-crash,
// no-mird.
//
// usage: [JET=<jet binary>] node Compiler/JetOptimizer/Tests/run-lint-corpus.mjs <outdir> [--case-list FILE]
// JET_LINT_ASSEMBLE_ONLY=1 writes the existing decoder/registry unit and exits.
// The native registry transport supplies the full checked-MIR corpus, builds
// this unit with production `jet build`, and requires a zero count per case.
// Writes <outdir>/lint.tsv and <outdir>/lint-summary.txt.
import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const repo = resolve(dirname(fileURLToPath(import.meta.url)), "../../..");
const { SUPPORT_ITEMS, jetDecoder, loadMirSchema } = await import(pathToFileURL(join(repo, "Compiler/JetBackend/Tests/mir-debug.mjs")));
const args = process.argv.slice(2);
const outDir = args.length ? resolve(args.shift()) : null;
if (!outDir) {
  console.error("usage: run-lint-corpus.mjs <outdir> [--case-list FILE]");
  process.exit(64);
}
let caseList = null;
for (let i = 0; i < args.length; i++) {
  if (args[i] === "--case-list") caseList = new Set(readFileSync(args[++i], "utf8").split("\n").map((stem) => stem.trim()).filter(Boolean));
  else throw new Error(`unknown option ${args[i]}`);
}
const lower = join(outDir, "lower");
const lintDir = join(outDir, "lint");
mkdirSync(lintDir, { recursive: true });

// 1. Assemble the unit.
const read = (path) => readFileSync(join(repo, path), "utf8");
// The top-level declaration whose line matches `head`, through its closing
// `}` at column 0 (or the line itself for a one-line item).
function item(path, head) {
  const lines = read(path).split("\n");
  const start = lines.findIndex((line) => head.test(line));
  if (start < 0) throw new Error(`${path}: no item matching ${head}`);
  if (lines[start].trimEnd().endsWith("}") || !lines[start].trimEnd().endsWith("{")) return lines[start];
  const end = lines.findIndex((line, index) => index > start && line === "}");
  return lines.slice(start, end + 1).join("\n");
}
const coreUses = new Set();
// One file without its `use jet_*` items; its `use core.*` lines are hoisted.
function body(path) {
  const kept = [];
  let skipping = false;
  for (const line of read(path).split("\n")) {
    if (skipping) {
      if (line.startsWith("]")) skipping = false;
      continue;
    }
    if (/^use jet_\w+\.\[\s*$/.test(line)) {
      skipping = true;
      continue;
    }
    if (/^use jet_\w+/.test(line)) continue;
    if (/^use core\./.test(line)) {
      coreUses.add(line);
      continue;
    }
    kept.push(line);
  }
  return `// [unit source: ${path}]\n${kept.join("\n")}\n`;
}
const support = [];
// Shared DerivationTypes declarations enter through SUPPORT_ITEMS, not MIR.jet.
for (const [path, names] of SUPPORT_ITEMS) for (const name of names) support.push(item(path, new RegExp(`^(pub )?(struct|enum) ${name}\\b`)));
support.push(item("Compiler/JetFoundation/Source/Types/Types.jet", /^(?:pub )?fn param_zone_name\(/));
const golden = "Compiler/JetBackend/Tests/GoldenLower.jet";
const reader = [/^struct MIRDReader\b/, /^fn mird_next\(/, /^fn mird_int\(/, /^fn mird_u64\(/, /^fn mird_bool\(/, /^fn mird_float\(/, /^fn mird_hex\(/, /^fn mird_string\(/].map((head) => item(golden, head));
for (const line of read(golden).split("\n")) if (/^use core\.math\b/.test(line)) coreUses.add(line);
const parts = [
  "// [unit source: Foundation items named by the Jet MIR schema]",
  ...support,
  "",
  body("Compiler/JetFoundation/Source/MIR/MIR.jet"),
  body("Compiler/JetOptimizer/Source/Verification/Lint.jet"),
  `// [unit source: ${golden} (.mird line reader)]`,
  ...reader,
  "",
  body("Compiler/JetOptimizer/Tests/LintCorpus.jet"),
  "// [unit source: decoder generated by Compiler/JetBackend/Tests/mir-debug.mjs]",
  jetDecoder(loadMirSchema(repo)),
];
writeFileSync(join(lintDir, "unit.jet"), [...coreUses, "", ...parts].join("\n"));
writeFileSync(join(lintDir, "package.jet"), 'name: "jet_optimizer_lint_corpus"\nversion: "0.1.0"\nauthority: { holds: { allow: [FS.Read, FS.Write, IO, Mem.Alloc] } }\n');
if (process.env.JET_LINT_ASSEMBLE_ONLY === "1") process.exit(0);

// 2. Lint every case in fresh processes of at most JET_LINT_BATCH cases.
const slugs = readdirSync(lower).filter((name) => name.endsWith(".mird")).map((name) => name.slice(0, -5)).sort();
const resultsPath = join(outDir, "results.tsv");
const stems = existsSync(resultsPath)
  ? new Map(readFileSync(resultsPath, "utf8").split("\n").filter(Boolean).map((line) => line.split("\t")[0]).map((stem) => [stem.replace(/[^A-Za-z0-9_-]+/gu, "_"), stem]))
  : new Map();
const cases = slugs.map((slug) => ({ slug, stem: stems.get(slug) ?? slug, verdict: "", detail: "" })).filter((c) => !caseList || caseList.has(c.stem));
for (const c of cases) rmSync(join(lower, `${c.slug}.lint`), { force: true });
const safeJet = `${process.env.HOME}/.cache/jet-dev/safe-jet.sh`;
const batch = Math.max(1, Number(process.env.JET_LINT_BATCH ?? "25"));
let pending = cases.slice();
while (pending.length) {
  const chunk = pending.slice(0, batch);
  writeFileSync(join(lintDir, "cases.txt"), chunk.map((c) => `../lower/${c.slug}`).join("\n") + "\n");
  const run = spawnSync(safeJet, ["run", "unit.jet"], {
    cwd: lintDir, encoding: "utf8", maxBuffer: 1 << 28,
    env: { ...process.env, SAFE_JET_MEM: process.env.JET_LINT_MEM ?? "4G", SAFE_JET_TIMEOUT: process.env.JET_LINT_TIMEOUT ?? "3600" },
  });
  writeFileSync(join(lintDir, `run-${Date.now()}.log`), `exit ${run.status}\n${run.stdout}\n${run.stderr}`);
  const finished = new Map();
  for (const line of (run.stdout ?? "").split("\n")) {
    const [name, count] = line.split("\t");
    if (count !== undefined && name.startsWith("../lower/")) finished.set(name.slice("../lower/".length), count);
  }
  for (const c of chunk) {
    if (!finished.has(c.slug)) continue;
    const count = finished.get(c.slug);
    if (count === "missing") c.verdict = "no-mird";
    else if (count === "0") c.verdict = "clean";
    else {
      c.verdict = "findings";
      c.detail = `${count}: ${readFileSync(join(lower, `${c.slug}.lint`), "utf8").split("\n")[0].slice(0, 200)}`;
    }
  }
  const left = chunk.filter((c) => !finished.has(c.slug));
  if (left.length) {
    // The first unfinished case stopped the process: blame it and go on.
    left[0].verdict = "lint-crash";
    left[0].detail = ((run.stderr ?? "").split("\n").find((line) => /error|panic/i.test(line)) ?? `exit ${run.status}`).slice(0, 200);
    console.log(`lint: ${left[0].stem} crashed (${left[0].detail})`);
  }
  pending = [...left.slice(1), ...pending.slice(chunk.length)];
  console.log(`lint: ${cases.length - pending.length}/${cases.length}`);
}

// 3. Receipt.
const counts = new Map();
for (const c of cases) counts.set(c.verdict, (counts.get(c.verdict) ?? 0) + 1);
writeFileSync(join(outDir, "lint.tsv"), cases.map((c) => `${c.stem}\t${c.verdict}\t${c.detail}`).join("\n") + "\n");
const rules = new Map();
for (const c of cases.filter((c) => c.verdict === "findings")) {
  for (const row of readFileSync(join(lower, `${c.slug}.lint`), "utf8").split("\n").filter(Boolean)) {
    const rule = row.split("\t")[0];
    if (!rules.has(rule)) rules.set(rule, new Set());
    rules.get(rule).add(c.stem);
  }
}
const failures = cases.filter((c) => c.verdict === "findings" || c.verdict === "lint-crash");
const summary = [
  `cases: ${cases.length}`,
  ...["clean", "findings", "lint-crash", "no-mird"].filter((verdict) => counts.has(verdict)).map((verdict) => `${verdict}: ${counts.get(verdict)}`),
  "",
  "cases with findings, by rule:",
  ...[...rules].sort((a, b) => b[1].size - a[1].size).map(([rule, set]) => `${set.size}\t${rule}`),
  "",
  `gate: ${failures.length ? `FAIL (${failures.length})` : "PASS"}`,
  ...failures.map((c) => `${c.verdict}\t${c.stem}\t${c.detail}`),
];
writeFileSync(join(outDir, "lint-summary.txt"), summary.join("\n") + "\n");
console.log(summary.join("\n"));
process.exit(failures.length ? 1 : 0);
