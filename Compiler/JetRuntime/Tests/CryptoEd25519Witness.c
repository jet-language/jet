// RFC 8032 section 7.1 public keys + FIPS 180-4 SHA-512 KATs.
#include <assert.h>
#include <stdint.h>
#include <stdio.h>
#include <string.h>
extern void jet_rt_alloc_init(void);
extern void jet_rt_ed25519_public_fixture(const void *, const void *);
extern void jet_rt_sha512_fixture(const void *, int64_t, const void *);
static unsigned char nibble(char c) {
    assert((c >= '0' && c <= '9') || (c >= 'a' && c <= 'f'));
    return (unsigned char)(c <= '9' ? c - '0' : c - 'a' + 10);
}
static void decode(unsigned char *out, size_t len, const char *hex) {
    assert(strlen(hex) == 2*len);
    for (size_t i = 0; i < len; ++i)
        out[i] = (unsigned char)((nibble(hex[2*i]) << 4) | nibble(hex[2*i+1]));
}
static void ed(const char *seed, const char *pub) {
    unsigned char k[32], expected[32];
    decode(k, 32, seed); decode(expected, 32, pub);
    jet_rt_ed25519_public_fixture(k, expected);
}
static void sha(const void *input, size_t len, const char *hex) {
    unsigned char expected[64]; decode(expected, 64, hex);
    jet_rt_sha512_fixture(input, (int64_t)len, expected);
}
