#!/usr/bin/env node
// Assembles the self-host lowering driver unit exactly as run-goldens.mjs
// assembles its golden unit (schema support items, MIR.jet, the backend, the
// generated decoder), with SelfHostLower.jet as the driver and a probe-only
// Mono.jet whose queue keeps going past preparation issues.
// usage: node assemble-lower.mjs <outdir> [repo]
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(process.argv[2] ?? "");
const repo = resolve(process.argv[3] ?? "/home/nate/Projects/Github/jet/.agent-worktrees/self-host-probe");
const { SUPPORT_ITEMS, jetDecoder, loadMirSchema } = await import(join(repo, "Compiler/JetBackend/Tests/mir-debug.mjs"));
const schema = loadMirSchema(repo);

const read = (path) => readFileSync(path.startsWith("/") ? path : join(repo, path), "utf8");
function item(path, name) {
  const lines = read(path).split("\n");
  const start = lines.findIndex((line) => new RegExp(`^(pub )?(struct|enum) ${name}\\b`).test(line));
  if (start < 0) throw new Error(`${path}: no declaration ${name}`);
  if (lines[start].trimEnd().endsWith("}")) return lines[start];
  const end = lines.findIndex((line, index) => index > start && line === "}");
  return lines.slice(start, end + 1).join("\n");
}

// Probe-only: the preparation queue records every issue and keeps its
// inventory, so one run reports all of them (the shipped queue stops at the
// first issue and drops the inventory: never a runnable subset).
const MONO_EDITS = [
  ["    loop cursor < q.pending.len() && q.issues.len() == 0 {\n", "    loop cursor < q.pending.len() {\n"],
  [
    "    if q.issues.len() > 0 {\n        q.functions = [LowerPreparedFunction]{}\n        q.instances = [MIRFunction]{}\n        q.mir_rows = [U64:Int]{}\n    }\n",
    "",
  ],
];
function transform(path, text) {
  if (!path.endsWith("/Lower/Mono.jet")) return text;
  for (const [from, to] of MONO_EDITS) {
    if (text.split(from).length !== 2) throw new Error(`Mono.jet: probe edit target not found exactly once: ${JSON.stringify(from.slice(0, 60))}`);
    text = text.replace(from, to);
  }
  return text;
}

const coreUses = new Set();
function body(path) {
  const kept = [];
  let skipping = false;
  for (const line of transform(path, read(path)).split("\n")) {
    if (skipping) {
      if (line.startsWith("]")) skipping = false;
      continue;
    }
    if (/^use jet_\w+\.\[\s*$/.test(line)) {
      skipping = true;
      continue;
    }
    if (/^use jet_\w+/.test(line)) continue;
    if (/^use core\./.test(line)) {
      coreUses.add(line);
      continue;
    }
    kept.push(line);
  }
  return `// [unit source: ${path}]\n${kept.join("\n")}\n`;
}

const sortedJet = (dir) => readdirSync(join(repo, dir)).filter((name) => name.endsWith(".jet")).sort().map((name) => `${dir}/${name}`);
const BACKEND = [
  "Compiler/JetFoundation/Source/Text/RustDebug.jet",
  "Compiler/JetBackend/Source/LIR/LIR.jet",
  "Compiler/JetBackend/Source/LIR/Lint.jet",
  "Compiler/JetBackend/Source/LIR/Print.jet",
  ...sortedJet("Compiler/JetBackend/Source/Lower"),
  "Compiler/JetBackend/Source/X64/Encoder.jet",
  "Compiler/JetBackend/Source/X64/RegAlloc.jet",
  "Compiler/JetBackend/Source/X64/Select.jet",
  "Compiler/JetBackend/Source/Image/Link.jet",
  "Compiler/JetBackend/Source/Image/Runtime.jet",
  "Compiler/JetBackend/Source/Image/RuntimeStrings.jet",
  "Compiler/JetBackend/Source/Image/ELF.jet",
  "Compiler/JetBackend/Source/Image/Object.jet",
  "Compiler/JetBackend/Source/Image/Archive.jet",
  "Compiler/JetBackend/Source/Image/StaticLink.jet",
  "Compiler/JetBackend/Source/Image/RuntimePack.jet",
];

const support = [];
for (const [path, names] of SUPPORT_ITEMS) for (const name of names) support.push(item(path, name));
const zone = read("Compiler/JetFoundation/Source/Types/Types.jet").split("\n");
const zoneStart = zone.findIndex((line) => line.startsWith("fn param_zone_name("));
support.push(zone.slice(zoneStart, zone.findIndex((line, index) => index > zoneStart && line === "}") + 1).join("\n"));
const parts = [
  "// [unit source: Foundation items named by the Jet MIR schema]",
  ...support,
  "",
  body("Compiler/JetFoundation/Source/MIR/MIR.jet"),
  ...BACKEND.map(body),
  body(join(here, "SelfHostLower.jet")),
  "// [unit source: decoder generated by Compiler/JetBackend/Tests/mir-debug.mjs]",
  jetDecoder(schema),
];
mkdirSync(out, { recursive: true });
writeFileSync(join(out, "unit.jet"), [...coreUses, "", ...parts].join("\n"));
writeFileSync(join(out, "package.jet"), 'name: "jet_selfhost_lower"\nversion: "0.1.0"\nauthority: { holds: { allow: [Env, FS.Read, FS.Write, IO, Mem.Alloc, Time] } }\n');
console.log(`assembled ${join(out, "unit.jet")} (${BACKEND.length} backend files)`);
